// Operands: bytes spread over the whole range, and as floats a mix of
// ordinary values of both signs, so the FP ops produce varied results.
static void init(struct st *s, int round) {
    static const float fv[3][4] = {
        {1.5f, -2.25f, 100.0f, -0.125f},
        {3.0f, 0.5f, -7.75f, 2.0f},
        {-1.0f, 4.5f, 0.25f, -3.5f},
    };
    if (round == 0) {
        for (int i = 0; i < 16; i++) {
            s->d[i] = (uint8_t) (0x11 * i + 3);
            s->n[i] = (uint8_t) (0xa5 ^ (i * 29));
            s->m[i] = (uint8_t) (i * 0x3b + 0x80);
        }
    } else {
        memcpy(s->d, fv[0], 16);
        memcpy(s->n, fv[1], 16);
        memcpy(s->m, fv[2], 16);
    }
}

static uint64_t fnv(uint64_t h, const uint8_t *p, size_t n) {
    for (size_t i = 0; i < n; i++)
        h = (h ^ p[i]) * 0x100000001b3ull;
    return h;
}

int main(int argc, char **argv) {
    test_init(argc, argv);
    unsigned n = sizeof(cases) / sizeof(cases[0]), bad = 0;
    for (unsigned i = 0; i < n; i++) {
        uint64_t h = 0xcbf29ce484222325ull;
        for (int round = 0; round < 2; round++) {
            for (int rep = 0; rep < 2; rep++) { // the second runs the translated block again
                struct st s;
                init(&s, round);
                cases[i].fn(&s);
                if (rep == 1)
                    h = fnv(h, s.d, 16);
            }
        }
#ifdef PRINT_GOLDEN
        printf("0x%016llxull, // %s\n", (unsigned long long) h, cases[i].insn);
#else
        if (h != golden[i]) {
            bad++;
            test_logf("  %-36s wrong\n", cases[i].insn);
        }
#endif
    }
#ifndef PRINT_GOLDEN
    if (sizeof(golden) / sizeof(golden[0]) != n)
        failf("golden table size", sizeof(golden) / sizeof(golden[0]), 0, 0, n, 0, 0);
    if (bad)
        failf("three-same results wrong", bad, 0, 0, 0, 0, 0);
    test_logf("  %u cases, %u wrong\n", n, bad);
    return finish_suite("simd_three_same");
#else
    return 0;
#endif
}

