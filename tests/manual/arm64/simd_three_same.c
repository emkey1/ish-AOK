// Operands: bytes spread over the whole range, and as floats a mix of
// ordinary values of both signs, so the FP ops produce varied results.
static void init(struct st *s, int round) {
    static const float fv[3][4] = {
        {1.5f, -2.25f, 100.0f, -0.125f},
        {3.0f, 0.5f, -7.75f, 2.0f},
        {-1.0f, 4.5f, 0.25f, -3.5f},
    };
    if (round == 0) {
        for (int i = 0; i < 16; i++) {
            s->d[i] = (uint8_t) (0x11 * i + 3);
            s->n[i] = (uint8_t) (0xa5 ^ (i * 29));
            s->m[i] = (uint8_t) (i * 0x3b + 0x80);
        }
    } else {
        memcpy(s->d, fv[0], 16);
        memcpy(s->n, fv[1], 16);
        memcpy(s->m, fv[2], 16);
    }
}

static uint64_t fnv(uint64_t h, const uint8_t *p, size_t n) {
    for (size_t i = 0; i < n; i++)
        h = (h ^ p[i]) * 0x100000001b3ull;
    return h;
}

