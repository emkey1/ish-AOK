// (16B and 8B) at every byte index. Each
// result (all of Vd, so a Q=0 op must clear the upper half and an
// accumulating op must read Vd) is hashed and compared with the value an
// Apple Silicon Mac computes running this same file natively: build it with
// -DPRINT_GOLDEN there to regenerate the table. Run once with
// `echo vspec=0 > /proc/ish/arm64_jit_fuse` to check the generic gadgets too.
