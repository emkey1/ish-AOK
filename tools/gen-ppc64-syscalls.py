#!/usr/bin/env python3
# Writes kernel/ppc64_syscalls.h: for each ppc64 system call number, the
# x86-64 one whose handler serves it. A ppc64 guest's calls run through the
# amd64 dispatch (kernel/calls.c, docs/ppc64le_guest_plan.md): the two ABIs
# have the same legacy calls and the same struct stat, and differ in their
# numbers. Matched by name, with the few calls powerpc names or shapes its
# own way mapped by hand below; kernel/calls.c's ppc64_syscall_args reorders
# the arguments of those that need it.
#
#   tools/gen-ppc64-syscalls.py PPC_UNISTD_64_H X86_64_UNISTD_64_H > kernel/ppc64_syscalls.h
#
# The headers are Linux's uapi asm/unistd_64.h for each, e.g. from Debian's
# linux-libc-dev-ppc64el-cross (/usr/powerpc64le-linux-gnu/include/asm/) and
# linux-libc-dev (/usr/include/x86_64-linux-gnu/asm/).
import re
import sys

# powerpc name -> the x86-64 call that does its job.
RENAMED = {
    'ugetrlimit': 'getrlimit',
    '_newselect': 'select',
    'waitpid': 'wait4',              # (pid, status, options, NULL)
    'umount': 'umount2',             # (path, 0)
    'statfs64': 'statfs',            # (path, size, buf) -> (path, buf)
    'fstatfs64': 'fstatfs',          # (fd, size, buf) -> (fd, buf)
    'sync_file_range2': 'sync_file_range',  # (fd, flags, off, n) -> (fd, off, n, flags)
    'send': 'sendto',                # (fd, buf, len, flags, NULL, 0)
    'recv': 'recvfrom',              # (fd, buf, len, flags, NULL, NULL)
}

# Numbers ppc64's own unistd_64.h lists that its syscall table has as
# sys_ni_syscall for 64-bit: ENOSYS on Linux, so no x86 handler may run them
# (modify_ldt would edit an x86 LDT).
NOT_ON_PPC64 = {'select', 'ioperm', 'iopl', 'modify_ldt'}


def load(path):
    calls = {}
    for m in re.finditer(r'#define __NR_(\w+)\s+(\d+)', open(path).read()):
        calls[m.group(1)] = int(m.group(2))
    return calls


ppc = load(sys.argv[1])
x86 = load(sys.argv[2])
count = max(ppc.values()) + 1
print('// Generated by tools/gen-ppc64-syscalls.py: one more than the x86-64 system')
print('// call that serves each ppc64 one (0: none; ENOSYS unless kernel/calls.c')
print('// handles it).')
print('#ifndef KERNEL_PPC64_SYSCALLS_H')
print('#define KERNEL_PPC64_SYSCALLS_H')
print()
print('#define PPC64_SYSCALL_COUNT %d' % count)
print()
print('static const short ppc64_syscall_amd64[PPC64_SYSCALL_COUNT] = {')
for name, nr in sorted(ppc.items(), key=lambda kv: kv[1]):
    target = RENAMED.get(name, name)
    if name in NOT_ON_PPC64:
        continue
    if target in x86:
        note = '' if target == name else ' -> %s' % target
        print('    [%d] = %d + 1, // %s%s' % (nr, x86[target], name, note))
print('};')
print()
print('#endif')
