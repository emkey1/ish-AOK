#!/usr/bin/env python3
# Generates tests/manual/x86/amd64_vex_float.c, or with --i386
# i386_vex_float.c (usage: this script [--i386] OUT.c).
#
# The VEX floating-point arithmetic (AVX: ADD SUB MUL DIV MIN MAX SQRT
# ADDSUB HADD HSUB and the bitwise/unpack ps/pd ops, packed and scalar),
# VEX.128 and VEX.256, register and memory, under seven MXCSR modes
# (rounding, FTZ, DAZ), against the same op's SSE form on the same machine:
# the result half by half and the MXCSR flags both halves raise. VCMP's 32
# predicates against a model of the SDM's table (the SSE form has only
# 0-7), flags included. camd runs this test too.
import sys
I386 = '--i386' in sys.argv
ARGS = [a for a in sys.argv[1:] if a != '--i386']
NAME = 'i386_vex_float' if I386 else 'amd64_vex_float'

PACKED = []
for op in 'add sub mul div min max'.split():
    for t in 'ps pd ss sd'.split():
        PACKED.append((op + t, op + t, 'bin', t))
for t in 'ps pd ss sd'.split():
    PACKED.append(('sqrt' + t, 'sqrt' + t, 'un' if t in ('ps', 'pd') else 'bin', t))
for op in 'addsubps addsubpd haddps haddpd hsubps hsubpd andps andpd andnps andnpd orps orpd xorps xorpd unpcklps unpcklpd unpckhps unpckhpd'.split():
    PACKED.append((op, op, 'bin', op[-2:]))
MODES = [0x1f80, 0x3f80, 0x5f80, 0x7f80, 0x9f80, 0x1fc0, 0x9fc0]

o = []; w = o.append
w(f'''// Generated by tools/gen-vex-float-test.py{" --i386" if I386 else ""} -- do not edit.
//
// The VEX floating-point ops against their SSE forms on the same machine,
// result and MXCSR flags, under seven MXCSR modes; VCMP's 32 predicates
// against a model (see the generator).
#pragma GCC target("avx2")
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

static unsigned long checks, bad;
static void check(const char *what, int k, unsigned mode, const uint8_t *got, const uint8_t *want, unsigned gf, unsigned wf) {{
    checks++;
    if ((memcmp(got, want, 32) != 0 || gf != wf) && bad++ < 40) {{
        printf("FAIL %s (%d, mxcsr %#x): flags %#x want %#x\\n  got ", what, k, mode, gf, wf);
        for (int i = 31; i >= 0; i--) printf("%s%02x", i % 8 == 7 ? " " : "", got[i]);
        printf("\\n  want");
        for (int i = 31; i >= 0; i--) printf("%s%02x", i % 8 == 7 ? " " : "", want[i]);
        printf("\\n");
    }}
}}
static uint64_t rs = 0x9e3779b97f4a7c15ull;
static uint64_t rnd(void) {{ rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17; return rs; }}
static void ldmx(unsigned v) {{ __asm__ volatile("ldmxcsr %0" :: "m"(v)); }}
static unsigned stmx(void) {{ unsigned v; __asm__ volatile("stmxcsr %0" : "=m"(v)); return v; }}

struct st {{ uint8_t a[32], b[32], d[32], out[32], m[64]; }} __attribute__((aligned(32)));
// special values, singles and doubles
static const uint32_t sv[] = {{0, 0x80000000, 0x3f800000, 0xbf800000, 0x7f800000, 0xff800000, 0x7fc00000,
    0xffc00001, 0x7f800001, 0xff812345, 0x00000001, 0x807fffff, 0x00400000, 0x7f7fffff, 0x00800000, 0x40490fdb}};
static const uint64_t dv[] = {{0, 0x8000000000000000ull, 0x3ff0000000000000ull, 0xbff0000000000000ull,
    0x7ff0000000000000ull, 0xfff0000000000000ull, 0x7ff8000000000000ull, 0xfff8000000000001ull,
    0x7ff0000000000001ull, 0xfff0000012345678ull, 1, 0x800fffffffffffffull, 0x0008000000000000ull,
    0x7fefffffffffffffull, 0x0010000000000000ull, 0x400921fb54442d18ull}};
static void fill(uint8_t *p, int dbl, int k) {{
    for (int i = 0; i < 32; i += dbl ? 8 : 4) {{
        uint64_t r = rnd();
        if ((r & 3) == 0) {{
            if (dbl) {{ uint64_t v = dv[(r >> 8) % 16]; memcpy(p + i, &v, 8); }}
            else {{ uint32_t v = sv[(r >> 8) % 16]; memcpy(p + i, &v, 4); }}
        }} else if (dbl) {{
            uint64_t v = (r >> 2) ^ ((uint64_t) (k % 3) << 62); memcpy(p + i, &v, 8);
        }} else {{
            uint32_t v = (uint32_t) (r >> 2) & 0xbfffffff; if (k & 1) v |= 0x30000000; memcpy(p + i, &v, 4);
        }}
    }}
}}
''')
# SSE references: x = x OP y (128), under the caller's mxcsr
for name, op, kind, t in PACKED:
    w(f'''static void sse_{name}(const uint8_t *x, const uint8_t *y, uint8_t *r) {{
    __asm__ volatile("movdqu (%0), %%xmm0\\n movdqu (%1), %%xmm1\\n {op} %%xmm1, %%xmm0\\n movdqu %%xmm0, (%2)"
                     :: "r"(x), "r"(y), "r"(r) : "memory", "xmm0", "xmm1");
}}''')
regs_pre = ('"vmovdqu (%0), %%ymm2\\n vmovdqu 32(%0), %%ymm3\\n vmovdqu 64(%0), %%ymm1\\n"')
forms = []
fi = 0
def vexfn(body):
    global fi
    w(f'''__attribute__((noinline)) static void f{fi}(struct st *t) {{
    __asm__ volatile({regs_pre}
                     "{body}\\n vmovdqu %%ymm1, 96(%0)\\n vzeroupper" :: "r"(t) : "memory", "xmm1", "xmm2", "xmm3");
}}''')
    fi += 1
    return fi - 1
for name, op, kind, t in PACKED:
    scalar = t in ('ss', 'sd')
    for L, x in ((256, 'ymm'), (128, 'xmm')):
        if scalar and L == 256:
            continue
        shapes = [('reg', f'v{op} %%{x}3, %%{x}2, %%{x}1', 'ab'), ('mem', f'v{op} 128(%0), %%{x}2, %%{x}1', 'am'),
                  ('d=s1', f'v{op} %%{x}3, %%{x}1, %%{x}1', 'db'), ('d=s2', f'v{op} %%{x}1, %%{x}2, %%{x}1', 'ad')]
        for lab, body, src in shapes:
            if kind == 'un':
                if lab.startswith('d='):
                    continue
                body = body.replace(f'%%{x}2, ', '')
            if scalar and lab == 'mem':
                pass
            i = vexfn(body)
            forms.append((i, f'v{op} {L} {lab}', f'sse_{name}', L, src, 0 if kind == 'bin' else 1, t, 0))
# VCMP, all 32 predicates
for t in 'ps pd ss sd'.split():
    for pred in range(32):
        for L, x in ((256, 'ymm'), (128, 'xmm')):
            if t in ('ss', 'sd') and L == 256:
                continue
            for lab, body, src in (('reg', f'vcmp{t} ${pred}, %%{x}3, %%{x}2, %%{x}1', 'ab'),
                                   ('mem', f'vcmp{t} ${pred}, 128(%0), %%{x}2, %%{x}1', 'am')):
                i = vexfn(body)
                forms.append((i, f'vcmp{t} {pred} {L} {lab}', 'NULL', L, src, 2, t, pred))
w('struct form { const char *name; void (*fn)(struct st *); void (*ref)(const uint8_t *, const uint8_t *, uint8_t *); int L, kind; const char *src; int dbl, scalar, pred; };')
w('static const struct form forms[] = {')
for i, name, ref, L, src, kind, t, pred in forms:
    dbl = 1 if t.endswith('d') else 0
    scalar = 1 if t in ('ss', 'sd') else 0
    w(f'    {{"{name}", f{i}, {ref}, {L}, {kind}, "{src}", {dbl}, {scalar}, {pred}}},')
w('};')
w(f'#define NFORMS {len(forms)}')
w(f'static const unsigned modes[] = {{{", ".join(hex(m) for m in MODES)}}};')
w(r'''
// VCMP's model: one lane, the predicate's result, and the flags (IE 1, DE 2)
static int isnan_b(uint64_t v, int dbl) { return dbl ? (v & 0x7fffffffffffffffull) > 0x7ff0000000000000ull : (v & 0x7fffffff) > 0x7f800000; }
static int issnan_b(uint64_t v, int dbl) { return isnan_b(v, dbl) && !(dbl ? (v >> 51) & 1 : (v >> 22) & 1); }
static int isden_b(uint64_t v, int dbl) { return dbl ? (v & 0x7ff0000000000000ull) == 0 && (v & 0xfffffffffffffull) : (v & 0x7f800000) == 0 && (v & 0x7fffff); }
static double val(uint64_t v, int dbl, int daz) {
    if (daz && isden_b(v, dbl)) return (v >> (dbl ? 63 : 31)) & 1 ? -0.0 : 0.0;
    if (dbl) { double d; memcpy(&d, &v, 8); return d; }
    float f; uint32_t u = (uint32_t) v; memcpy(&f, &u, 4); return f;
}
static int cmp_model(int pred, uint64_t a, uint64_t b, int dbl, int daz, unsigned *flags) {
    int un = isnan_b(a, dbl) || isnan_b(b, dbl);
    int sig = ((0x6666 >> (pred & 15)) & 1) ^ (pred >> 4);
    if (issnan_b(a, dbl) || issnan_b(b, dbl) || (sig && un)) *flags |= 1;
    if (!daz && !un && (isden_b(a, dbl) || isden_b(b, dbl))) *flags |= 2;
    if (un) return (0x8778 >> (pred & 15)) & 1;
    double x = val(a, dbl, daz), y = val(b, dbl, daz);
    switch (pred & 7) {
    case 0: return x == y;
    case 1: return x < y;
    case 2: return x <= y;
    case 3: return 0;
    case 4: return x != y;
    case 5: return x >= y;
    case 6: return x > y;
    default: return 1;
    }
}

int main(void) {
    static struct st t;
    for (int k = 0; k < 60; k++) {
        for (unsigned mi = 0; mi < sizeof modes / sizeof modes[0]; mi++) {
            unsigned mode = modes[mi];
            for (int fi = 0; fi < NFORMS; fi++) {
                const struct form *f = &forms[fi];
                fill(t.a, f->dbl, k); fill(t.b, f->dbl, k); fill(t.d, f->dbl, k); fill(t.m, f->dbl, k); fill(t.m + 32, f->dbl, k);
                if (k % 5 == 1) memcpy(t.b, t.a, 32);
                struct st in = t;
                ldmx(mode);
                f->fn(&t);
                unsigned gf = stmx() & 0x3f;
                const uint8_t *s1 = f->src[0] == 'd' ? in.d : in.a;
                const uint8_t *s2 = f->src[1] == 'm' ? in.m : f->src[1] == 'd' ? in.d : in.b;
                uint8_t want[32] = {0};
                unsigned wf = 0;
                if (f->kind < 2) {
                    ldmx(mode);
                    if (f->kind == 0) f->ref(s1, s2, want); else f->ref(s2, s2, want);
                    wf = stmx() & 0x3f;
                    if (f->L == 256) {
                        ldmx(mode);
                        if (f->kind == 0) f->ref(s1 + 16, s2 + 16, want + 16); else f->ref(s2 + 16, s2 + 16, want + 16);
                        wf |= stmx() & 0x3f;
                    }
                } else {
                    int n = f->L / 8, lb = f->dbl ? 8 : 4, daz = (mode >> 6) & 1;
                    if (f->scalar) { n = 16; memcpy(want, s1, 16); }
                    for (int i = 0; i < (f->scalar ? lb : n); i += lb) {
                        uint64_t a = 0, b = 0;
                        memcpy(&a, s1 + i, lb); memcpy(&b, s2 + i, lb);
                        uint64_t r = cmp_model(f->pred, a, b, f->dbl, daz, &wf) ? ~0ull : 0;
                        memcpy(want + i, &r, lb);
                    }
                }
                check(f->name, k, mode, t.out, want, gf, wf);
            }
        }
    }
    ldmx(0x1f80);
    printf("NAME: %s (%d forms, %lu checks, %lu mismatches)\n", bad ? "FAIL" : "PASS", NFORMS, checks, bad);
    return bad != 0;
}''')
open(ARGS[0], 'w').write('\n'.join(o).replace('NAME: %s', NAME + ': %s'))
print(len(forms), 'forms')
