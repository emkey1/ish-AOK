#!/usr/bin/env python3
# Generates tests/manual/x86/amd64_0f_rm.c (usage: this script OUT.c).
import sys
CC = ['o', 'no', 'b', 'ae', 'e', 'ne', 'be', 'a', 's', 'ns', 'p', 'np', 'l', 'ge', 'le', 'g']
SUF = {16: 'w', 32: 'l', 64: 'q'}
R = {  # (dst, src) per register set and size
    0: {16: ('%%dx', '%%ax'), 32: ('%%edx', '%%eax'), 64: ('%%rdx', '%%rax'), 8: '%%dl'},
    1: {16: ('%%r9w', '%%r10w'), 32: ('%%r9d', '%%r10d'), 64: ('%%r9', '%%r10'), 8: '%%r9b'},
}
o = []; w = o.append
w('''// Generated by tools/gen-amd64-0f-rm-test.py -- do not edit.
//
// The 0F r/m group: CMOVcc, SETcc, BT/BTS/BTR/BTC (register and imm8 bit
// offsets, register and memory bases, LOCK), SHLD/SHRD (imm8 and CL),
// IMUL r, r/m, BSF/BSR/TZCNT/LZCNT -- 16/32/64 bits, register (rdx/rax and
// r9/r10) and memory forms, against a model of the SDM built from adds, shifts
// and masks only (no multiply, no bit-scan, no double shift: those are the
// instructions under test). Only the flags the SDM defines are checked; the
// model is checked against real hardware (an AMD Ryzen, which has BMI1 and
// LZCNT, so F3 0F BC/BD are TZCNT/LZCNT, as AOK runs them).
#include <stdint.h>
#include <stdio.h>
#include <string.h>

static unsigned long checks, bad;
static void check(const char *what, long k, uint64_t got, uint64_t want) {
    checks++;
    if (got != want && bad++ < 40)
        printf("FAIL %s (%ld): %#llx, want %#llx\\n", what, k, (unsigned long long) got, (unsigned long long) want);
}
#define CF 0x1
#define PF 0x4
#define AF 0x10
#define ZF 0x40
#define SF 0x80
#define OF 0x800
#define ST (CF | PF | AF | ZF | SF | OF)
static uint64_t rs = 0x243f6a8885a308d3ull;
static uint64_t rnd(void) { rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17; return rs; }
static uint64_t mask(int bits) { return bits == 64 ? ~0ull : (1ull << bits) - 1; }
static int bit(uint64_t v, int i) { return (v >> i) & 1; }
static int64_t sext(uint64_t v, int bits) { return bits == 64 ? (int64_t) v : (int64_t) (v << (64 - bits)) >> (64 - bits); }
static int parity(uint64_t v) { int p = 1; for (int i = 0; i < 8; i++) p ^= bit(v, i); return p; }
static int cond(int c, uint64_t f) {
    int cf = !!(f & CF), zf = !!(f & ZF), sf = !!(f & SF), of = !!(f & OF), pf = !!(f & PF), r;
    switch (c >> 1) {
    case 0: r = of; break;
    case 1: r = cf; break;
    case 2: r = zf; break;
    case 3: r = cf | zf; break;
    case 4: r = sf; break;
    case 5: r = pf; break;
    case 6: r = sf != of; break;
    default: r = zf | (sf != of); break;
    }
    return (c & 1) ? !r : r;
}
// a register write of `bits`: 32 zero-extends, 16 keeps the rest
static uint64_t wr(uint64_t old, uint64_t v, int bits) {
    return bits == 32 ? (v & mask(32)) : bits == 64 ? v : (old & ~mask(bits)) | (v & mask(bits));
}
// signed a*b as 128 bits from 32-bit limbs, adds and shifts only
static void smul(int64_t a, int64_t b, uint64_t *lo, uint64_t *hi) {
    uint64_t ua = (uint64_t) a, ub = (uint64_t) b, l[4] = {0};
    int neg = 0;
    if (a < 0) { ua = -ua; neg ^= 1; }
    if (b < 0) { ub = -ub; neg ^= 1; }
    for (int i = 0; i < 64; i++) {
        if (!bit(ub, i)) continue;
        // add ua << i into l[] (32-bit limbs in uint64)
        uint64_t sh[4] = {0}, x0 = ua & 0xffffffffull, x1 = ua >> 32;
        int q = i / 32, r = i % 32;
        uint64_t p0 = x0 << r, p1 = x1 << r;            // each < 2^64
        uint64_t s0 = p0 & 0xffffffffull, s1 = (p0 >> 32) + (p1 & 0xffffffffull), s2 = p1 >> 32;
        s2 += s1 >> 32; s1 &= 0xffffffffull;
        if (q + 0 < 4) sh[q] += s0;
        if (q + 1 < 4) sh[q + 1] += s1;
        if (q + 2 < 4) sh[q + 2] += s2;
        uint64_t c = 0;
        for (int j = 0; j < 4; j++) { l[j] += sh[j] + c; c = l[j] >> 32; l[j] &= 0xffffffffull; }
    }
    uint64_t L = l[0] | (l[1] << 32), H = l[2] | (l[3] << 32);
    if (neg) { L = ~L; H = ~H; L += 1; if (L == 0) H += 1; }
    *lo = L; *hi = H;
}
''')
forms = []  # dicts
def add(**k): forms.append(k)
for bits in (16, 32, 64):
    s = SUF[bits]
    for c, cc in enumerate(CC):
        for rset in (0, 1):
            d, sr = R[rset][bits]
            add(name=f'cmov{cc}{s} r{rset}', fam='cmov', bits=bits, cc=c, mem=0, rset=rset, asm=f'cmov{cc}{s} {sr}, {d}')
        add(name=f'cmov{cc}{s} mem', fam='cmov', bits=bits, cc=c, mem=1, rset=0, asm=f'cmov{cc}{s} (%%rsi), {R[0][bits][0]}')
for c, cc in enumerate(CC):
    add(name=f'set{cc} dl', fam='set', bits=8, cc=c, mem=0, rset=0, high=0, asm=f'set{cc} %%dl')
    add(name=f'set{cc} dh', fam='set', bits=8, cc=c, mem=0, rset=0, high=1, asm=f'set{cc} %%dh')
    add(name=f'set{cc} r9b', fam='set', bits=8, cc=c, mem=0, rset=1, high=0, asm=f'set{cc} %%r9b')
    add(name=f'set{cc} mem', fam='set', bits=8, cc=c, mem=1, rset=0, high=0, asm=f'set{cc} (%%rsi)')
for bits in (16, 32, 64):
    s = SUF[bits]
    for b, op in enumerate(['bt', 'bts', 'btr', 'btc']):
        for rset in (0, 1):
            d, sr = R[rset][bits]
            add(name=f'{op}{s} reg,r r{rset}', fam='bt', op=b, bits=bits, imm=None, mem=0, rset=rset, asm=f'{op}{s} {sr}, {d}')
            add(name=f'{op}{s} imm,r r{rset}', fam='bt', op=b, bits=bits, imm=True, mem=0, rset=rset, asm=f'{op}{s} $IMM, {d}')
        add(name=f'{op}{s} reg,mem', fam='bt', op=b, bits=bits, imm=None, mem=1, rset=0, asm=f'{op}{s} {R[0][bits][1]}, (%%rsi)')
        add(name=f'{op}{s} imm,mem', fam='bt', op=b, bits=bits, imm=True, mem=1, rset=0, asm=f'{op}{s} $IMM, (%%rsi)')
        if b:
            add(name=f'lock {op}{s} reg,mem', fam='bt', op=b, bits=bits, imm=None, mem=1, rset=0, asm=f'lock {op}{s} {R[0][bits][1]}, (%%rsi)')
            add(name=f'lock {op}{s} imm,mem', fam='bt', op=b, bits=bits, imm=True, mem=1, rset=0, asm=f'lock {op}{s} $IMM, (%%rsi)')
    for left, op in ((1, 'shld'), (0, 'shrd')):
        for kind in ('imm', 'cl'):
            cnt = '$IMM' if kind == 'imm' else '%%cl'
            for rset in (0, 1):
                d, sr = R[rset][bits]
                add(name=f'{op}{s} {kind} r{rset}', fam='dsh', left=left, kind=kind, bits=bits, mem=0, rset=rset, asm=f'{op}{s} {cnt}, {sr}, {d}')
            add(name=f'{op}{s} {kind} mem', fam='dsh', left=left, kind=kind, bits=bits, mem=1, rset=0, asm=f'{op}{s} {cnt}, {R[0][bits][1]}, (%%rsi)')
    for rset in (0, 1):
        d, sr = R[rset][bits]
        add(name=f'imul{s} r,r r{rset}', fam='imul', bits=bits, mem=0, rset=rset, asm=f'imul{s} {sr}, {d}')
    add(name=f'imul{s} mem,r', fam='imul', bits=bits, mem=1, rset=0, asm=f'imul{s} (%%rsi), {R[0][bits][0]}')
    for k, op in enumerate(['bsf', 'bsr', 'tzcnt', 'lzcnt']):
        for rset in (0, 1):
            d, sr = R[rset][bits]
            add(name=f'{op}{s} r,r r{rset}', fam='scan', op=k, bits=bits, mem=0, rset=rset, asm=f'{op}{s} {sr}, {d}')
        add(name=f'{op}{s} mem,r', fam='scan', op=k, bits=bits, mem=1, rset=0, asm=f'{op}{s} (%%rsi), {R[0][bits][0]}')
# CMPXCHG / XADD with a register destination: rax is the accumulator, rdx
# the destination, rcx the source (r9 and r10 in the second set).
XR = {8: [('%%cl', '%%dl', 0, 0), ('%%ch', '%%dh', 1, 1), ('%%cl', '%%dh', 0, 1), ('%%ch', '%%dl', 1, 0)],
      16: [('%%cx', '%%dx', 0, 0)], 32: [('%%ecx', '%%edx', 0, 0)], 64: [('%%rcx', '%%rdx', 0, 0)]}
X9 = {8: '%%r10b, %%r9b', 16: '%%r10w, %%r9w', 32: '%%r10d, %%r9d', 64: '%%r10, %%r9'}
xforms = []
for bits in (8, 16, 32, 64):
    s = {8: 'b', 16: 'w', 32: 'l', 64: 'q'}[bits]
    for op in ('cmpxchg', 'xadd'):
        for src, dst, sh, dh in XR[bits]:
            xforms.append(dict(name=f'{op}{s} {src[2:]},{dst[2:]}', op=op == 'xadd', bits=bits, sh=sh, dh=dh, r9=0,
                               asm=f'{op}{s} {src}, {dst}'))
        xforms.append(dict(name=f'{op}{s} r10,r9', op=op == 'xadd', bits=bits, sh=0, dh=0, r9=1,
                           asm=f'mov %2, %%r10\\n mov %1, %%r9\\n {op}{s} {X9[bits]}\\n mov %%r9, %1\\n mov %%r10, %2'))
FAM = {'cmov': 0, 'set': 1, 'bt': 2, 'dsh': 3, 'imul': 4, 'scan': 5}
for i, f in enumerate(forms):
    f['immv'] = (i * 37 + 5) % 256 if f['fam'] == 'bt' else 1 + (i * 7) % (16 if f['bits'] == 16 else 63)
    a = f['asm'].replace('$IMM', '$%d' % f['immv'])
    if f['rset'] == 1:
        a = f'mov %1, %%r9\\n mov %2, %%r10\\n {a}\\n mov %%r9, %1'
    w(f'''__attribute__((noinline)) static void f{i}(uint64_t *d, uint64_t s, uint8_t *mem, uint64_t cl, uint64_t *fl) {{
    uint64_t rd = *d, f, fin = *fl;
    __asm__ volatile("push %5\\n popfq\\n {a}\\n pushfq\\n pop %0"
                     : "=&r"(f), "+d"(rd) : "a"(s), "c"(cl), "S"(mem), "r"(fin) : "cc", "memory", "r9", "r10");
    *d = rd; *fl = f;
}}''')
w('struct form { const char *name; int fam, bits, sub, mem, rset, aux; void (*fn)(uint64_t *, uint64_t, uint8_t *, uint64_t, uint64_t *); unsigned imm; };')
w('static const struct form forms[] = {')
for i, f in enumerate(forms):
    sub = f.get('cc', f.get('op', f.get('left', 0)))
    aux = {'set': f.get('high', 0), 'bt': 1 if f.get('imm') else 0, 'dsh': 1 if f.get('kind') == 'cl' else 0}.get(f['fam'], 0)
    if f['fam'] == 'bt' and f['name'].startswith('lock'):
        aux |= 2
    w(f'    {{"{f["name"]}", {FAM[f["fam"]]}, {f["bits"]}, {sub}, {f["mem"]}, {f["rset"]}, {aux}, f{i}, {f["immv"]}}},')
w('};')
w(f'#define NFORMS {len(forms)}')
for i, f in enumerate(xforms):
    w(f'''__attribute__((noinline)) static void x{i}(uint64_t *d, uint64_t *a, uint64_t *c, uint64_t *fl) {{
    uint64_t rd = *d, ra = *a, rc = *c, f, fin = *fl;
    __asm__ volatile("push %4\\n popfq\\n {f['asm']}\\n pushfq\\n pop %0"
                     : "=&r"(f), "+d"(rd), "+c"(rc), "+a"(ra) : "r"(fin) : "cc", "memory", "r9", "r10");
    *d = rd; *a = ra; *c = rc; *fl = f;
}}''')
w('struct xform { const char *name; int xadd, bits, sh, dh, r9; void (*fn)(uint64_t *, uint64_t *, uint64_t *, uint64_t *); };')
w('static const struct xform xforms[] = {')
for i, f in enumerate(xforms):
    w(f'    {{"{f["name"]}", {int(f["op"])}, {f["bits"]}, {f["sh"]}, {f["dh"]}, {f["r9"]}, x{i}}},')
w('};')
w(f'#define NXFORMS {len(xforms)}')
w('''
#define BUF 512
#define MID 256
static uint64_t pick(int k) {
    switch (k % 8) {
    case 0: return 0;
    case 1: return 1ull << (rnd() % 64);
    case 2: return rnd() & rnd() & rnd();
    case 3: return ~0ull;
    case 4: return 0x8000000000000000ull >> (rnd() % 4);
    default: return rnd();
    }
}

int main(void) {
    static uint8_t buf[BUF] __attribute__((aligned(16))), want[BUF];
    for (int k = 0; k < 400; k++) {
        for (int fi = 0; fi < NFORMS; fi++) {
            const struct form *f = &forms[fi];
            int bits = f->bits;
            uint64_t m = mask(bits), msb = 1ull << (bits - 1);
            uint64_t d = pick(k + fi), s = pick(k * 3 + fi + 1), cl = rnd() & 0xff;
            if (k % 7 == 0) cl &= 0x3f;
            for (int i = 0; i < BUF; i++) buf[i] = rnd();
            uint8_t *mem = buf + MID + (k % 8);
            uint64_t memv = pick(k * 5 + fi + 2);
            memcpy(mem, &memv, 8);
            if (f->fam == 2 && f->mem && !(f->aux & 1)) {
                // a bit-string offset reaching up to 1 KiB-bit either side
                s = (uint64_t) (int64_t) ((int) (rnd() % 2048) - 1024);
                if (bits == 16) s = (s & 0xffff) | (rnd() << 16);
                if (bits == 32) s = (s & 0xffffffffull) | (rnd() << 32);
            }
            uint64_t fin = 0x202 | (rnd() & ST);
            memcpy(want, buf, BUF);
            uint64_t d0 = d, fl = fin;
            f->fn(&d, s, mem, cl, &fl);
            uint64_t wd = d0, wf = fin, def = ST;
            int skip = 0;
            switch (f->fam) {
            case 0: { // CMOVcc: the destination is written either way
                uint64_t src = f->mem ? memv : s;
                wd = wr(d0, cond(f->sub, fin) ? src : d0, bits);
                break;
            }
            case 1: { // SETcc
                uint64_t v = cond(f->sub, fin);
                if (f->mem) want[MID + (k % 8)] = v;
                else if (f->aux) wd = (d0 & ~0xff00ull) | (v << 8);
                else wd = (d0 & ~0xffull) | v;
                break;
            }
            case 2: { // BT*
                int op = f->sub, cf;
                def = CF;
                if (!f->mem) {
                    unsigned b = (f->aux & 1 ? f->imm : (unsigned) s) & (bits - 1);
                    cf = bit(d0, b);
                    uint64_t v = d0 & m;
                    if (op == 1) v |= 1ull << b; else if (op == 2) v &= ~(1ull << b); else if (op == 3) v ^= 1ull << b;
                    wd = op ? wr(d0, v, bits) : d0;
                } else {
                    int64_t off = f->aux & 1 ? (int64_t) (f->imm & (bits - 1)) : sext(s, bits);
                    // bit `off` of the little-endian string at mem
                    int64_t byte = MID + (k % 8) + (off >> 3);
                    int b = off & 7;
                    cf = (want[byte] >> b) & 1;
                    if (op == 1) want[byte] |= 1 << b; else if (op == 2) want[byte] &= ~(1 << b); else if (op == 3) want[byte] ^= 1 << b;
                }
                wf = (fin & ~(uint64_t) CF) | (cf ? CF : 0);
                break;
            }
            case 3: { // SHLD/SHRD
                unsigned c = (f->aux ? (unsigned) cl : f->imm) & (bits == 64 ? 63 : 31);
                uint64_t dst = (f->mem ? memv : d0) & m, src = s & m, r = 0;
                if (c == 0) { // nothing changes; a 32-bit register is still written
                    if (!f->mem) wd = wr(d0, d0, bits);
                    break;
                }
                if (c > (unsigned) bits) { skip = 1; break; }      // 16-bit, 17..31: undefined
                for (int j = 0; j < bits; j++) {
                    int v;
                    if (f->sub) v = j >= (int) c ? bit(dst, j - c) : bit(src, bits - c + j);
                    else v = j + (int) c < bits ? bit(dst, j + c) : bit(src, j + c - bits);
                    r |= (uint64_t) v << j;
                }
                int cfv = f->sub ? bit(dst, bits - c) : bit(dst, c - 1);
                wf = fin & ~(uint64_t) ST;
                wf |= (cfv ? CF : 0) | (r == 0 ? ZF : 0) | (r & msb ? SF : 0) | (parity(r) ? PF : 0);
                if (c == 1 && (((r ^ dst) & msb) != 0)) wf |= OF;
                def &= ~(uint64_t) AF;
                if (c != 1) def &= ~(uint64_t) OF;
                if (f->mem) { uint64_t nv = (memv & ~m) | r; memcpy(&want[MID + (k % 8)], &nv, 8); }
                else wd = wr(d0, r, bits);
                break;
            }
            case 4: { // IMUL r, r/m
                uint64_t lo, hi;
                smul(sext(d0, bits), sext(f->mem ? memv : s, bits), &lo, &hi);
                int ov = bits == 64 ? hi != (uint64_t) ((int64_t) lo >> 63) : (uint64_t) sext(lo, bits) != lo || hi != (uint64_t) ((int64_t) lo >> 63);
                wd = wr(d0, lo, bits);
                wf = (fin & ~(uint64_t) (CF | OF)) | (ov ? CF | OF : 0);
                def = CF | OF;
                break;
            }
            case 5: { // BSF BSR TZCNT LZCNT
                uint64_t src = (f->mem ? memv : s) & m;
                int op = f->sub, lo = -1, hi = -1;
                for (int j = 0; j < bits; j++) if (bit(src, j)) { if (lo < 0) lo = j; hi = j; }
                if (op < 2) {
                    def = ZF;
                    wf = (fin & ~(uint64_t) ZF) | (src == 0 ? ZF : 0);
                    // a zero source leaves the destination alone (AMD documents it;
                    // Intel hardware does the same) -- not even a 32-bit zero-extension
                    if (src) wd = wr(d0, op == 0 ? lo : hi, bits);
                } else {
                    uint64_t r = src == 0 ? bits : op == 2 ? lo : bits - 1 - hi;
                    def = CF | ZF;
                    wf = (fin & ~(uint64_t) (CF | ZF)) | (src == 0 ? CF : 0) | (r == 0 ? ZF : 0);
                    wd = wr(d0, r, bits);
                }
                break;
            }
            }
            if (skip) continue;
            long id = fi * 1000 + k;
            check(f->name, id, fl & def, wf & def);
            check(f->name, id, d, wd);
            check(f->name, id, memcmp(buf, want, BUF), 0);
        }
    }
    for (int k = 0; k < 4000; k++) {
        for (int fi = 0; fi < NXFORMS; fi++) {
            const struct xform *f = &xforms[fi];
            int bits = f->bits;
            uint64_t m = mask(bits), msb = 1ull << (bits - 1);
            uint64_t d = pick(k + fi), a = pick(k * 3 + fi + 1), c = rnd();
            uint64_t fin = 0x202 | (rnd() & ST);
            // the byte/word values the instruction sees
            int dsh = f->dh ? 8 : 0, ssh = f->sh ? 8 : 0;
            if (!f->xadd && (k & 1)) {           // make the compare succeed half the time
                uint64_t dv = (d >> dsh) & m;
                a = (a & ~m) | dv;
            }
            uint64_t d0 = d, a0 = a, c0 = c, fl = fin;
            f->fn(&d, &a, &c, &fl);
            uint64_t dv = (d0 >> dsh) & m, sv = (c0 >> ssh) & m;
            uint64_t wd = d0, wa = a0, wc = c0, lhs, rhs, res;
            int sub;
            if (f->xadd) {
                lhs = dv; rhs = sv; sub = 0;
            } else {
                lhs = a0 & m; rhs = dv; sub = 1;
            }
            res = (sub ? lhs - rhs : lhs + rhs) & m;
            int cf = sub ? lhs < rhs : res < lhs;
            int of = sub ? ((lhs ^ rhs) & (lhs ^ res) & msb) != 0 : (~(lhs ^ rhs) & (lhs ^ res) & msb) != 0;
            uint64_t wf = fin & ~(uint64_t) ST;
            wf |= (cf ? CF : 0) | (of ? OF : 0) | (res == 0 ? ZF : 0) | (res & msb ? SF : 0) |
                  (parity(res) ? PF : 0) | (((lhs ^ rhs ^ res) >> 4) & 1 ? AF : 0);
            // a byte register is AL..BL or AH..BH of its slot; wider ones follow wr()
            #define PUT(old, v, sh) (bits == 8 ? (((old) & ~(0xffull << (sh))) | (((v) & 0xff) << (sh))) : wr((old), (v), bits))
            if (f->xadd) {
                wc = PUT(c0, dv, ssh);
                wd = PUT(d0, res, dsh);
            } else if ((a0 & m) == dv) {
                wd = PUT(d0, sv, dsh);
            } else {
                wa = PUT(a0, dv, 0);
            }
            long id = 1000000 + fi * 10000 + k;
            check(f->name, id, fl & ST, wf & ST);
            check(f->name, id, d, wd);
            check(f->name, id, a, wa);
            check(f->name, id, c, wc);
        }
    }
    printf("amd64_0f_rm: %s (%d forms, %lu checks, %lu mismatches)\\n", bad ? "FAIL" : "PASS", NFORMS + NXFORMS, checks, bad);
    return bad != 0;
}''')
open(sys.argv[1], 'w').write('\n'.join(o))
print(len(forms), 'forms')
