#!/usr/bin/env python3
"""Record what is inside a shipped root filesystem image.

A GPL source offer is only worth something if, years later, we can say exactly
which upstream package versions were in a given build and where they came
from. Nothing else in this repository records that, and it is unrecoverable
once the image is rebuilt -- so run this for every image we ship and keep the
output with the release.

    tools/root-manifest.py devuan-minirootfs-6.0-aarch64.tar.xz
    tools/root-manifest.py *.tar.xz -o docs/root-manifests

Reads the package database out of the image without extracting it:
Alpine's lib/apk/db/installed (which carries a licence per package) or
Debian/Devuan's var/lib/dpkg/status (which does not -- the licence is in
/usr/share/doc/<pkg>/copyright, and the source package is what you fetch).
"""

import argparse
import hashlib
import io
import os
import re
import sys
import tarfile

# Files worth copying into the manifest verbatim: they say where the packages
# came from, which is half of what a source request needs.
PROVENANCE = [
    "etc/alpine-release",
    "etc/apk/repositories",
    "etc/debian_version",
    "etc/os-release",
    "etc/apt/sources.list",
]
APK_DB = "lib/apk/db/installed"
DPKG_DB = "var/lib/dpkg/status"


def read_members(path, wanted):
    """One pass over the archive; returns {name: text} for the names present."""
    found = {}
    with tarfile.open(path, "r:*") as tf:
        for member in tf:
            if not member.isfile():
                continue
            name = member.name.lstrip("./")
            if name in wanted:
                data = tf.extractfile(member).read()
                found[name] = data.decode("utf-8", "replace")
                if len(found) == len(wanted):
                    break
    return found


def parse_apk(text):
    """Alpine: blank-line separated, P: name V: version L: licence."""
    out = []
    for block in text.split("\n\n"):
        name = re.search(r"^P:(.+)$", block, re.M)
        if not name:
            continue
        ver = re.search(r"^V:(.+)$", block, re.M)
        lic = re.search(r"^L:(.+)$", block, re.M)
        orig = re.search(r"^o:(.+)$", block, re.M)  # origin = source package
        out.append({
            "package": name.group(1).strip(),
            "version": ver.group(1).strip() if ver else "?",
            "source": orig.group(1).strip() if orig else name.group(1).strip(),
            "licence": lic.group(1).strip() if lic else "?",
        })
    return out


def parse_dpkg(text):
    """Debian/Devuan: RFC822 blocks. Source: is absent when it equals Package:."""
    out = []
    for block in text.split("\n\n"):
        name = re.search(r"^Package: (.+)$", block, re.M)
        ver = re.search(r"^Version: (.+)$", block, re.M)
        if not (name and ver):
            continue
        src = re.search(r"^Source: (\S+)", block, re.M)
        out.append({
            "package": name.group(1).strip(),
            "version": ver.group(1).strip(),
            "source": src.group(1).strip() if src else name.group(1).strip(),
            "licence": "",  # not in the status file; see the note in the output
        })
    return out


def digest(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def manifest_for(path):
    found = read_members(path, set(PROVENANCE) | {APK_DB, DPKG_DB})

    if APK_DB in found:
        kind, packages = "Alpine (apk)", parse_apk(found[APK_DB])
    elif DPKG_DB in found:
        kind, packages = "Debian/Devuan (dpkg)", parse_dpkg(found[DPKG_DB])
    else:
        raise SystemExit("%s: no apk or dpkg database inside" % path)

    packages.sort(key=lambda p: p["package"])
    has_licence = any(p["licence"] for p in packages)

    o = io.StringIO()
    w = o.write
    w("# %s\n\n" % os.path.basename(path))
    w("Generated by `tools/root-manifest.py`. Keep this with the release: it is\n")
    w("what lets us answer a GPL source request for this exact image.\n\n")
    w("| | |\n|---|---|\n")
    w("| Image | `%s` |\n" % os.path.basename(path))
    w("| SHA-256 | `%s` |\n" % digest(path))
    w("| Size | %d bytes |\n" % os.path.getsize(path))
    w("| Packaging | %s |\n" % kind)
    w("| Packages | %d |\n\n" % len(packages))

    provenance = [n for n in PROVENANCE if n in found]
    if provenance:
        w("## Where the packages came from\n\n")
        for name in provenance:
            body = found[name].strip()
            if body:
                w("`/%s`:\n\n```\n%s\n```\n\n" % (name, body))

    w("## Packages\n\n")
    if has_licence:
        w("| Package | Version | Source package | Licence |\n|---|---|---|---|\n")
        for p in packages:
            w("| %s | `%s` | %s | %s |\n"
              % (p["package"], p["version"], p["source"], p["licence"]))
    else:
        w("The dpkg status file records no licence; for a source request, fetch\n")
        w("the source package named below at the version given, from the archive\n")
        w("listed above. The licence is in `/usr/share/doc/<package>/copyright`.\n\n")
        w("| Package | Version | Source package |\n|---|---|---|\n")
        for p in packages:
            w("| %s | `%s` | %s |\n" % (p["package"], p["version"], p["source"]))
    return o.getvalue()


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("images", nargs="+", help="rootfs tarballs")
    ap.add_argument("-o", "--out-dir", help="write <image>.md here instead of stdout")
    args = ap.parse_args()

    for path in args.images:
        text = manifest_for(path)
        if args.out_dir:
            os.makedirs(args.out_dir, exist_ok=True)
            base = os.path.basename(path)
            for suffix in (".tar.xz", ".tar.gz", ".tar.bz2", ".tar"):
                if base.endswith(suffix):
                    base = base[: -len(suffix)]
                    break
            dest = os.path.join(args.out_dir, base + ".md")
            with io.open(dest, "w", encoding="utf-8") as f:
                f.write(text)
            print("wrote %s" % dest)
        else:
            sys.stdout.write(text)


if __name__ == "__main__":
    main()
