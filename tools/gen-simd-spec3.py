#!/usr/bin/env python3
"""Write jit/guest-arm64/simd_spec3.S: the arm64 guest's AdvSIMD three-same
gadgets specialised by arrangement, and arm64_vs3_index, which maps each
generic gadget (simd_arith.S, simd.S's bitwise ones) to its table of them.

    python3 tools/gen-simd-spec3.py [OUTPUT]

The op lists below mirror simd_arith.S's instantiations and gen.c's validity
classes; add an op to both.
"""

import sys

# name, host mnemonic, validity class: D = every size (.1d rejected by gen.c),
# NOD = no 64-bit elements, HS = 16/32-bit only, B = bytes only; ACC = reads Vd.
INT_OPS = """
vadd add D
vsub sub D
vmul mul NOD
vpmul pmul B
vcmeq cmeq D
vcmtst cmtst D
vcmgt cmgt D
vcmge cmge D
vcmhi cmhi D
vcmhs cmhs D
vsmax smax NOD
vsmin smin NOD
vumax umax NOD
vumin umin NOD
vsabd sabd NOD
vuabd uabd NOD
vshadd shadd NOD
vuhadd uhadd NOD
vsrhadd srhadd NOD
vurhadd urhadd NOD
vshsub shsub NOD
vuhsub uhsub NOD
vsshl sshl D
vushl ushl D
vsrshl srshl D
vurshl urshl D
vsqshl sqshl D
vuqshl uqshl D
vsqrshl sqrshl D
vuqrshl uqrshl D
vsqadd sqadd D
vuqadd uqadd D
vsqsub sqsub D
vuqsub uqsub D
vsqdmulh sqdmulh HS
vsqrdmulh sqrdmulh HS
vaddp addp D
vsmaxp smaxp NOD
vsminp sminp NOD
vumaxp umaxp NOD
vuminp uminp NOD
vmla mla NOD ACC
vmls mls NOD ACC
vsaba saba NOD ACC
vuaba uaba NOD ACC
"""

FP_OPS = """
vfadd fadd
vfsub fsub
vfmul fmul
vfdiv fdiv
vfmulx fmulx
vfmax fmax
vfmin fmin
vfmaxnm fmaxnm
vfminnm fminnm
vfaddp faddp
vfmaxp fmaxp
vfminp fminp
vfmaxnmp fmaxnmp
vfminnmp fminnmp
vfrecps frecps
vfrsqrts frsqrts
vfcmeq fcmeq
vfcmge fcmge
vfcmgt fcmgt
vfacge facge
vfacgt facgt
vfabd fabd
vfmla fmla ACC
vfmls fmls ACC
"""

# Bitwise: generic gadgets are per arrangement (<name>_8b, <name>_16b).
LOGIC_OPS = """
vand and
vbic bic
vorr orr
vorn orn
veor eor
vbsl bsl ACC
vbit bit ACC
vbif bif ACC
"""

# By-element (indexed) multiplies, vector: Vm.T[i] is loaded with ld1r from
# its precomputed offset and the plain vector op runs. FP = .2s/.4s/.2d,
# HS = .4h/.8h/.2s/.4s. Indexed by size*2+Q like the integer ops.
ELEM_OPS = """
velem_fmul fmul FP
velem_fmulx fmulx FP
velem_fmla fmla FP ACC
velem_fmls fmls FP ACC
velem_mul mul HS
velem_mla mla HS ACC
velem_mls mls HS ACC
"""

INT_ARR = ["8b", "16b", "4h", "8h", "2s", "4s", None, "2d"]   # size*2+Q
FP_ARR = ["2s", "4s", None, "2d", None, None, None, None]      # sz*2+Q
LOGIC_ARR = ["8b", "16b", None, None, None, None, None, None]  # Q

HEADER = r"""// AArch64 guest AdvSIMD three-same gadgets specialised by arrangement, fed
// precomputed cpu_state offsets: the per-arrangement twins of simd_arith.S's
// generic three-same gadgets (and simd.S's bitwise ones), which decode
// Rd/Rn/Rm, size and Q on every execution and branch on the arrangement.
// Here the arrangement is in the gadget and the registers are offsets, so an
// `add v0.4s, v1.4s, v2.4s` is two loads, the host instruction and a store.
//
// GENERATED by tools/gen-simd-spec3.py from the op lists there; edit those.
//
// Code stream: [gadget][d_off][n_off][m_off], byte offsets of the V
// registers from _cpu, each its own word (plain loads beat unpacking one
// packed word; see alu_spec.S). A Q=0 arrangement's
// host op zeroes v0's upper half, as the architecture zeroes Vd's, so the
// whole q0 is stored either way. Accumulating ops (MLA, SABA, FMLA, BSL...)
// read Vd too.
//
// arm64_vs3_index pairs each generic gadget with its table of specialised
// ones, 8 entries: integer ops by size*2+Q (8b 16b 4h 8h 2s 4s - 2d), FP ops
// by sz*2+Q (2s 4s - 2d), bitwise ops by Q (8b 16b); 0 where the arrangement
// does not exist. gen.c's gen_arm64_vs3 looks the generic gadget up there
// when the "vspec" bit of /proc/ish/arm64_jit_fuse is on.
//
// arm64_vse_index does the same for the by-element (indexed) multiplies
// (FMUL/FMULX/FMLA/FMLS, MUL/MLA/MLS): the third offset is the element's,
// which the gadget replicates with ld1r before the plain vector op --
// exactly the indexed op's arithmetic.

#include "gadgets.h"

.macro vs3 name, op, arr
.gadget vs3_\name\()_\arr
    ldp x9, x10, [_ip]
    ldr x11, [_ip, #16]
    ldr q0, [_cpu, x10]
    ldr q1, [_cpu, x11]
    \op v0.\arr, v0.\arr, v1.\arr
    str q0, [_cpu, x9]
    gret 3
.endm

.macro vs3acc name, op, arr
.gadget vs3_\name\()_\arr
    ldp x9, x10, [_ip]
    ldr x11, [_ip, #16]
    ldr q0, [_cpu, x9]
    ldr q1, [_cpu, x10]
    ldr q2, [_cpu, x11]
    \op v0.\arr, v1.\arr, v2.\arr
    str q0, [_cpu, x9]
    gret 3
.endm

.macro vse name, op, arr
.gadget vse_\name\()_\arr
    ldp x9, x10, [_ip]
    ldr x11, [_ip, #16]
    add x11, _cpu, x11
    ldr q0, [_cpu, x10]
    ld1r {v1.\arr}, [x11]
    \op v0.\arr, v0.\arr, v1.\arr
    str q0, [_cpu, x9]
    gret 3
.endm

.macro vseacc name, op, arr
.gadget vse_\name\()_\arr
    ldp x9, x10, [_ip]
    ldr x11, [_ip, #16]
    add x11, _cpu, x11
    ldr q0, [_cpu, x9]
    ldr q1, [_cpu, x10]
    ld1r {v2.\arr}, [x11]
    \op v0.\arr, v1.\arr, v2.\arr
    str q0, [_cpu, x9]
    gret 3
.endm

.text
"""


def int_valid(cls, i):
    size = i // 2
    if INT_ARR[i] is None:
        return False
    return {"D": True, "NOD": size < 3, "HS": size in (1, 2), "B": size == 0}[cls]


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else "jit/guest-arm64/simd_spec3.S"
    body, tables, index = [], [], []

    def emit(name, op, acc, arrs, generics):
        ents = []
        for a in arrs:
            if a is None:
                ents.append("0")
                continue
            body.append("%s %s, %s, %s" % ("vs3acc" if acc else "vs3", name, op, a))
            ents.append("NAME(gadget_arm64_vs3_%s_%s)" % (name, a))
        tables.append((name, ents))
        for g in generics:
            index.append((g, name))

    for line in INT_OPS.strip().splitlines():
        f = line.split()
        name, op, cls, acc = f[0], f[1], f[2], "ACC" in f[3:]
        emit(name, op, acc, [INT_ARR[i] if int_valid(cls, i) else None for i in range(8)], [name])
    for line in FP_OPS.strip().splitlines():
        f = line.split()
        emit(f[0], f[1], "ACC" in f[2:], FP_ARR, [f[0]])
    for line in LOGIC_OPS.strip().splitlines():
        f = line.split()
        emit(f[0], f[1], "ACC" in f[2:], LOGIC_ARR, [f[0] + "_8b", f[0] + "_16b"])

    etables, eindex = [], []
    for line in ELEM_OPS.strip().splitlines():
        f = line.split()
        name, op, cls, acc = f[0], f[1], f[2], "ACC" in f[3:]
        arrs = [None, None, "4h", "8h", "2s", "4s", None, "2d"]
        if cls == "FP":
            arrs[2] = arrs[3] = None
        else:
            arrs[7] = None
        ents = []
        for a in arrs:
            if a is None:
                ents.append("0")
                continue
            body.append("%s %s, %s, %s" % ("vseacc" if acc else "vse", name, op, a))
            ents.append("NAME(gadget_arm64_vse_%s_%s)" % (name, a))
        etables.append((name, ents))
        eindex.append((name, name))

    out = [HEADER]
    out += body
    out.append("\n.data\n.balign 8")
    for name, ents in tables:
        out.append("Lvs3tab_%s:\n    .quad %s" % (name, ", ".join(ents)))
    out.append(".global NAME(arm64_vs3_index)\nNAME(arm64_vs3_index):")
    for generic, name in index:
        out.append("    .quad NAME(gadget_arm64_%s), Lvs3tab_%s" % (generic, name))
    out.append("    .quad 0, 0\n")
    for name, ents in etables:
        out.append("Lvsetab_%s:\n    .quad %s" % (name, ", ".join(ents)))
    out.append("// By-element ops: the element's offset is the third field.")
    out.append(".global NAME(arm64_vse_index)\nNAME(arm64_vse_index):")
    for generic, name in eindex:
        out.append("    .quad NAME(gadget_arm64_%s), Lvsetab_%s" % (generic, name))
    out.append("    .quad 0, 0\n")
    with open(out_path, "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
