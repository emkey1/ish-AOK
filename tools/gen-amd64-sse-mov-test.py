#!/usr/bin/env python3
# Generates tests/manual/x86/amd64_sse_mov.c (usage: this script OUT.c).
import sys
o = []; w = o.append
w('''// Generated by tools/gen-amd64-sse-mov-test.py -- do not edit.
//
// MMX and SSE2 moves and the integer odds and ends: MOVD/MOVQ between
// MMX/XMM and GPRs or memory (0F 6E/7E, REX.W), MOVQ mm (0F 6F/7F), MOVQ xmm
// (F3 0F 7E, 66 0F D6), MOVQ2DQ/MOVDQ2Q (F3/F2 0F D6), MOVNTQ/MOVNTDQ (E7),
// PMOVMSKB (D7), PEXTRW/PINSRW (C5/C4), PSHUFW (0F 70), MASKMOVQ/MASKMOVDQU
// (F7) -- MMX and XMM, xmm9/r9 (REX), register and memory -- each checked
// against what the SDM says lands where. Checked on real hardware (an AMD
// Ryzen).
#include <setjmp.h>
#include <signal.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

// An instruction the emulator does not know must not hide the rest: SIGILL
// is caught, counted as that form's failure, and the run goes on.
static sigjmp_buf jb;
static void on_ill(int sig) { (void) sig; siglongjmp(jb, 1); }

static unsigned long checks, bad;
static void check(const char *what, long k, uint64_t got, uint64_t want) {
    checks++;
    if (got != want && bad++ < 40)
        printf("FAIL %s (%ld): %#llx, want %#llx\\n", what, k, (unsigned long long) got, (unsigned long long) want);
}
static uint64_t rs = 0x243f6a8885a308d3ull;
static uint64_t rnd(void) { rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17; return rs; }

// The state an op sees and leaves: v = the xmm/mm destination (16 bytes,
// MMX uses 8), s = the xmm/mm source, m = 32 bytes of memory at rsi, g = rdx.
struct st { uint8_t v[16], s[16], m[32]; uint64_t g; };
''')
# Each form: asm (operands: %0 = &st), and a model in C operating on struct st.
# Registers: dst = xmm1/mm1 (or xmm9 in r forms), src = xmm2/mm2, gpr = rdx/r9.
F = []
def add(name, asm, model, mmx):
    F.append((name, asm, model, mmx))
# MOVD/MOVQ to/from GPR and memory
add('movd edx->mm', 'movd %%edx, %%mm1', 'memset(t->v, 0, 8); memcpy(t->v, &t->g, 4);', 1)
add('movq rdx->mm', 'movq %%rdx, %%mm1', 'memcpy(t->v, &t->g, 8);', 1)
add('movd m32->mm', 'movd (%%rsi), %%mm1', 'memset(t->v, 0, 8); memcpy(t->v, t->m, 4);', 1)
add('movd mm->edx', 'movd %%mm1, %%edx', 'uint32_t x; memcpy(&x, t->v, 4); t->g = x;', 1)
add('movq mm->rdx', 'movq %%mm1, %%rdx', 'memcpy(&t->g, t->v, 8);', 1)
add('movd mm->m32', 'movd %%mm1, (%%rsi)', 'memcpy(t->m, t->v, 4);', 1)
add('movd edx->xmm', 'movd %%edx, %%xmm1', 'memset(t->v, 0, 16); memcpy(t->v, &t->g, 4);', 0)
add('movq rdx->xmm', 'movq %%rdx, %%xmm1', 'memset(t->v, 0, 16); memcpy(t->v, &t->g, 8);', 0)
add('movd m32->xmm', 'movd (%%rsi), %%xmm1', 'memset(t->v, 0, 16); memcpy(t->v, t->m, 4);', 0)
add('movd xmm->edx', 'movd %%xmm1, %%edx', 'uint32_t x; memcpy(&x, t->v, 4); t->g = x;', 0)
add('movq xmm->rdx', 'movq %%xmm1, %%rdx', 'memcpy(&t->g, t->v, 8);', 0)
add('movd xmm->m32', 'movd %%xmm1, (%%rsi)', 'memcpy(t->m, t->v, 4);', 0)
add('movq r9->xmm9', 'mov %%rdx, %%r9\\n movq %%r9, %%xmm9\\n movdqa %%xmm9, %%xmm1', 'memset(t->v, 0, 16); memcpy(t->v, &t->g, 8);', 0)
# MOVQ mm
add('movq mm2->mm1', 'movq %%mm2, %%mm1', 'memcpy(t->v, t->s, 8);', 1)
add('movq m64->mm', 'movq (%%rsi), %%mm1', 'memcpy(t->v, t->m, 8);', 1)
add('movq mm->m64', 'movq %%mm1, (%%rsi)', 'memcpy(t->m, t->v, 8);', 1)
add('movq mm,mm 7f', '.byte 0x0f, 0x7f, 0xd1', 'memcpy(t->v, t->s, 8);', 1)          # 0F 7F /r mod 3: rm (mm1) <- reg (mm2)
# MOVQ xmm
add('movq xmm2->xmm1 f3', 'movq %%xmm2, %%xmm1', 'memcpy(t->v, t->s, 8); memset(t->v + 8, 0, 8);', 0)
add('movq m64->xmm', 'movq (%%rsi), %%xmm1', 'memcpy(t->v, t->m, 8); memset(t->v + 8, 0, 8);', 0)
add('movq xmm->m64 d6', 'movq %%xmm1, (%%rsi)', 'memcpy(t->m, t->v, 8);', 0)
add('movq xmm,xmm d6', '.byte 0x66, 0x0f, 0xd6, 0xca', 'memcpy(t->v + 0, t->v, 0); { uint8_t lo[8]; memcpy(lo, t->s, 8); memcpy(t->s, t->v, 8); memset(t->s + 8, 0, 8); (void) lo; }', 0)  # d6 /r: xmm2 <- xmm1 low, zero high
add('movq2dq', 'movq2dq %%mm2, %%xmm1', 'memcpy(t->v, t->s, 8); memset(t->v + 8, 0, 8);', 2)   # src mm2, dst xmm1
add('movdq2q', 'movdq2q %%xmm2, %%mm1', 'memcpy(t->v, t->s, 8);', 3)                           # src xmm2, dst mm1
# non-temporal stores
add('movntq', 'movntq %%mm1, (%%rsi)', 'memcpy(t->m, t->v, 8);', 1)
add('movntdq', 'movntdq %%xmm1, (%%rsi)', 'memcpy(t->m, t->v, 16);', 0)
# PMOVMSKB
add('pmovmskb mm', 'pmovmskb %%mm1, %%edx', 't->g = 0; for (int i = 0; i < 8; i++) t->g |= (uint64_t) (t->v[i] >> 7) << i;', 1)
add('pmovmskb xmm', 'pmovmskb %%xmm1, %%edx', 't->g = 0; for (int i = 0; i < 16; i++) t->g |= (uint64_t) (t->v[i] >> 7) << i;', 0)
add('pmovmskb xmm9->r9', 'movdqa %%xmm1, %%xmm9\\n pmovmskb %%xmm9, %%r9d\\n mov %%r9, %%rdx', 't->g = 0; for (int i = 0; i < 16; i++) t->g |= (uint64_t) (t->v[i] >> 7) << i;', 0)
# PEXTRW / PINSRW
for i in (0, 1, 2, 3, 5, 7):
    add(f'pextrw mm {i}', f'pextrw ${i}, %%mm1, %%edx', f't->g = t->v[({i} & 3) * 2] | (t->v[({i} & 3) * 2 + 1] << 8);', 1)
    add(f'pextrw xmm {i}', f'pextrw ${i}, %%xmm1, %%edx', f't->g = t->v[{i} * 2] | (t->v[{i} * 2 + 1] << 8);', 0)
    add(f'pinsrw mm r {i}', f'pinsrw ${i}, %%edx, %%mm1', f't->v[({i} & 3) * 2] = (uint8_t) t->g; t->v[({i} & 3) * 2 + 1] = (uint8_t) (t->g >> 8);', 1)
    add(f'pinsrw xmm r {i}', f'pinsrw ${i}, %%edx, %%xmm1', f't->v[{i} * 2] = (uint8_t) t->g; t->v[{i} * 2 + 1] = (uint8_t) (t->g >> 8);', 0)
    add(f'pinsrw xmm m {i}', f'pinsrw ${i}, (%%rsi), %%xmm1', f't->v[{i} * 2] = t->m[0]; t->v[{i} * 2 + 1] = t->m[1];', 0)
    add(f'pinsrw mm m {i}', f'pinsrw ${i}, (%%rsi), %%mm1', f't->v[({i} & 3) * 2] = t->m[0]; t->v[({i} & 3) * 2 + 1] = t->m[1];', 1)
# PSHUFW
for imm in (0x1b, 0xe4, 0x00, 0xff, 0x9c):
    add(f'pshufw {imm:#x}', f'pshufw ${imm}, %%mm2, %%mm1',
        f'for (int i = 0; i < 4; i++) {{ int k = ({imm} >> (2 * i)) & 3; t->v[2 * i] = t->s[2 * k]; t->v[2 * i + 1] = t->s[2 * k + 1]; }}', 1)
    add(f'pshufw m {imm:#x}', f'pshufw ${imm}, (%%rsi), %%mm1',
        f'for (int i = 0; i < 4; i++) {{ int k = ({imm} >> (2 * i)) & 3; t->v[2 * i] = t->m[2 * k]; t->v[2 * i + 1] = t->m[2 * k + 1]; }}', 1)
# MASKMOVQ / MASKMOVDQU: bytes of v where the mask (s) byte has its top bit, to [rdi]
add('maskmovq', 'push %%rdi\\n mov %%rsi, %%rdi\\n maskmovq %%mm2, %%mm1\\n pop %%rdi', 'for (int i = 0; i < 8; i++) if (t->s[i] & 0x80) t->m[i] = t->v[i];', 1)
add('maskmovdqu', 'push %%rdi\\n mov %%rsi, %%rdi\\n maskmovdqu %%xmm2, %%xmm1\\n pop %%rdi', 'for (int i = 0; i < 16; i++) if (t->s[i] & 0x80) t->m[i] = t->v[i];', 0)

for i, (name, asm, model, mmx) in enumerate(F):
    # load v/s into the registers the form uses, run, store them back
    if mmx == 1:
        pre = 'movq (%0), %%mm1\\n movq 16(%0), %%mm2\\n'
        post = '\\n movq %%mm1, (%0)\\n movq %%mm2, 16(%0)\\n emms'
    elif mmx == 2:   # movq2dq: mm2 -> xmm1
        pre = 'movdqu (%0), %%xmm1\\n movq 16(%0), %%mm2\\n'
        post = '\\n movdqu %%xmm1, (%0)\\n emms'
    elif mmx == 3:   # movdq2q: xmm2 -> mm1
        pre = 'movq (%0), %%mm1\\n movdqu 16(%0), %%xmm2\\n'
        post = '\\n movq %%mm1, (%0)\\n emms'
    else:
        pre = 'movdqu (%0), %%xmm1\\n movdqu 16(%0), %%xmm2\\n'
        post = '\\n movdqu %%xmm1, (%0)\\n movdqu %%xmm2, 16(%0)'
    w(f'''__attribute__((noinline)) static void f{i}(struct st *t) {{
    __asm__ volatile("mov 64(%0), %%rdx\\n lea 32(%0), %%rsi\\n {pre} {asm}{post}\\n mov %%rdx, 64(%0)"
                     :: "r"(t) : "memory", "rdx", "rsi", "r9", "xmm1", "xmm2", "xmm9", "mm1", "mm2");
}}
static void m{i}(struct st *t) {{ {model} }}''')
w('static const struct { const char *name; int mmx; void (*fn)(struct st *), (*model)(struct st *); } forms[] = {')
for i, (name, asm, model, mmx) in enumerate(F):
    w(f'    {{"{name}", {mmx}, f{i}, m{i}}},')
w('};')
w(f'#define NFORMS {len(F)}')
w('''
int main(void) {
    static struct st t __attribute__((aligned(16))), want;
    struct sigaction sa;
    memset(&sa, 0, sizeof(sa));
    sa.sa_handler = on_ill;
    sa.sa_flags = SA_NODEFER;
    sigaction(SIGILL, &sa, NULL);
    for (int k = 0; k < 4000; k++) {
        for (int fi = 0; fi < NFORMS; fi++) {
            for (int i = 0; i < 16; i++) { t.v[i] = (uint8_t) rnd(); t.s[i] = (uint8_t) rnd(); }
            for (int i = 0; i < 32; i++) t.m[i] = (uint8_t) rnd();
            t.g = rnd();
            if (forms[fi].mmx == 1 || forms[fi].mmx == 3) { memset(t.v + 8, 0, 8); }
            if (forms[fi].mmx == 1 || forms[fi].mmx == 2) { memset(t.s + 8, 0, 8); }
            want = t;
            if (sigsetjmp(jb, 1)) {
                check(forms[fi].name, fi * 10000 + k, 0xbad, 0);    // SIGILL
                __asm__ volatile("emms");
                continue;
            }
            forms[fi].fn(&t);
            forms[fi].model(&want);
            uint64_t a, b;
            for (int q = 0; q < 2; q++) {
                memcpy(&a, t.v + 8 * q, 8); memcpy(&b, want.v + 8 * q, 8); check(forms[fi].name, fi * 10000 + k, a, b);
                memcpy(&a, t.s + 8 * q, 8); memcpy(&b, want.s + 8 * q, 8); check(forms[fi].name, fi * 10000 + k, a, b);
            }
            for (int q = 0; q < 4; q++) { memcpy(&a, t.m + 8 * q, 8); memcpy(&b, want.m + 8 * q, 8); check(forms[fi].name, fi * 10000 + k, a, b); }
            check(forms[fi].name, fi * 10000 + k, t.g, want.g);
        }
    }
    printf("amd64_sse_mov: %s (%d forms, %lu checks, %lu mismatches)\\n", bad ? "FAIL" : "PASS", NFORMS, checks, bad);
    return bad != 0;
}''')
open(sys.argv[1], 'w').write('\n'.join(o))
print(len(F), 'forms')
