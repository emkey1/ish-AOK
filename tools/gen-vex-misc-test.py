#!/usr/bin/env python3
# Generates tests/manual/x86/amd64_vex_misc.c, or with --i386
# i386_vex_misc.c (usage: this script [--i386] OUT.c).
#
# VBLENDVPS/PD and VPBLENDVB (the mask register in imm8[7:4]) against a byte
# model; VLDMXCSR/VSTMXCSR (a round trip, a reserved bit #GP); VPCMPESTRI/M
# and VPCMPISTRI/M against their SSE forms on the same machine (ECX, xmm0,
# EFLAGS), the M forms zeroing ymm0's upper half. camd runs it too.
import sys
I386 = '--i386' in sys.argv
ARGS = [a for a in sys.argv[1:] if a != '--i386']
NAME = 'i386_vex_misc' if I386 else 'amd64_vex_misc'
C = 'e' if I386 else 'r'
o = []; w = o.append
w(f'''// Generated by tools/gen-vex-misc-test.py{" --i386" if I386 else ""} -- do not edit.
//
// VBLENDV*, VLDMXCSR/VSTMXCSR, VPCMPxSTRx (see the generator).
#pragma GCC target("avx2")
#define _GNU_SOURCE
#include <setjmp.h>
#include <signal.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
static unsigned long checks, bad;
static uint64_t rs = 0x9e3779b97f4a7c15ull;
static uint64_t rnd(void) {{ rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17; return rs; }}
struct st {{ uint8_t a[32], b[32], d[32], out[32], m[64], k[32], x0[32]; uint64_t cx, fl, ax, dx; }} __attribute__((aligned(32)));
''')
F = []
for op, lb in (('vblendvps', 4), ('vblendvpd', 8), ('vpblendvb', 1)):
    for L, x in ((256, 'ymm'), (128, 'xmm')):
        n = L // 8
        model = f'memcpy(o, a, {n}); for (int i = 0; i < {n}; i += {lb}) if (k[i + {lb - 1}] & 0x80) memcpy(o + i, S + i, {lb});'
        F.append((f'{op} {L} reg', f'{op} %%{x}4, %%{x}3, %%{x}2, %%{x}1', model.replace('S', 'b')))
        F.append((f'{op} {L} mem', f'{op} %%{x}4, 128(%0), %%{x}2, %%{x}1', model.replace('S', 'm')))
for i, (name, asm, model) in enumerate(F):
    w(f'''__attribute__((noinline)) static void f{i}(struct st *t) {{
    __asm__ volatile("vmovdqu (%0), %%ymm2\\n vmovdqu 32(%0), %%ymm3\\n vmovdqu 64(%0), %%ymm1\\n vmovdqu 192(%0), %%ymm4\\n"
                     "{asm}\\n vmovdqu %%ymm1, 96(%0)\\n vzeroupper" :: "r"(t) : "memory", "xmm1", "xmm2", "xmm3", "xmm4");
}}
static void m{i}(const uint8_t *a, const uint8_t *b, const uint8_t *m, const uint8_t *k, uint8_t *o) {{ (void) b; (void) m; {model} }}''')
PC = []
for op in ('pcmpestri', 'pcmpestrm', 'pcmpistri', 'pcmpistrm'):
    for imm in (0x00, 0x0c, 0x18, 0x01, 0x44, 0x3a, 0x62, 0x70, 0x0d, 0x45):
        for mem in (0, 1):
            src = '128(%0)' if mem else '%%xmm3'
            for vex in (0, 1):
                nm = f'{"v" if vex else ""}{op}'
                body = (f'"vmovdqu (%0), %%xmm2\\n vmovdqu 32(%0), %%xmm3\\n vmovdqu 224(%0), %%ymm0\\n mov 272(%0), %%{C}ax\\n mov 280(%0), %%{C}dx\\n mov $0x5555, %%ecx\\n'
                        f' push $0x8d7\\n popf\\n {nm} ${imm}, {src}, %%xmm2\\n pushf\\n pop 264(%0)\\n mov %%{C}cx, 256(%0)\\n vmovdqu %%ymm0, 224(%0)\\n vzeroupper"')
                w(f'__attribute__((noinline)) static void p{len(PC)}_{vex}(struct st *t) {{ __asm__ volatile({body} :: "r"(t) : "memory", "cc", "{C}ax", "{C}cx", "{C}dx", "xmm0", "xmm2", "xmm3"); }}')
            PC.append((f'v{op} {imm:#x} {"mem" if mem else "reg"}', op.endswith('m')))
w('static const struct { const char *name; void (*fn)(struct st *); void (*model)(const uint8_t *, const uint8_t *, const uint8_t *, const uint8_t *, uint8_t *); } forms[] = {')
for i, (name, asm, model) in enumerate(F):
    w(f'    {{"{name}", f{i}, m{i}}},')
w('};')
w('static const struct { const char *name; void (*vex)(struct st *), (*sse)(struct st *); int mask; } pforms[] = {')
for i, (name, mask) in enumerate(PC):
    w(f'    {{"{name}", p{i}_1, p{i}_0, {1 if mask else 0}}},')
w('};')
w(f'#define NF {len(F)}\n#define NP {len(PC)}')
w(r'''
static sigjmp_buf jb;
static volatile int sig;
static void on_segv(int s) { sig = s; siglongjmp(jb, 1); }
int main(void) {
    static struct st t, u;
    for (int k = 0; k < 400; k++) {
        for (int fi = 0; fi < NF; fi++) {
            for (int i = 0; i < 32; i++) { t.a[i] = (uint8_t) rnd(); t.b[i] = (uint8_t) rnd(); t.d[i] = (uint8_t) rnd(); t.k[i] = (uint8_t) rnd(); }
            for (int i = 0; i < 64; i++) t.m[i] = (uint8_t) rnd();
            u = t;
            forms[fi].fn(&t);
            uint8_t o[32] = {0};
            forms[fi].model(u.a, u.b, u.m, u.k, o);
            checks++;
            if (memcmp(t.out, o, 32) && bad++ < 40) printf("FAIL %s (%d)\n", forms[fi].name, k);
        }
        for (int pi = 0; pi < NP; pi++) {
            int alpha = 1 + (int) (rnd() % 6);
            for (int i = 0; i < 32; i++) { t.a[i] = (uint8_t) ('a' + rnd() % alpha); t.b[i] = (uint8_t) ('a' + rnd() % alpha); t.m[i] = t.b[i]; t.x0[i] = (uint8_t) rnd(); }
            if (k % 3 == 0) t.a[rnd() % 16] = 0;
            if (k % 3 == 1) { t.b[rnd() % 16] = 0; memcpy(t.m, t.b, 16); }
            t.ax = rnd() % 20; t.dx = rnd() % 20;
            u = t;
            pforms[pi].vex(&t);
            pforms[pi].sse(&u);
            if (pforms[pi].mask) memset(u.x0 + 16, 0, 16);   // VEX.128: ymm0's upper half zeroed
            checks++;
            if ((t.cx != u.cx || (t.fl & 0x8d5) != (u.fl & 0x8d5) || memcmp(t.x0, u.x0, 32)) && bad++ < 40)
                printf("FAIL %s (%d): ecx %llx want %llx, flags %llx want %llx, xmm0 %s\n", pforms[pi].name, k,
                       (unsigned long long) t.cx, (unsigned long long) u.cx, (unsigned long long) (t.fl & 0x8d5),
                       (unsigned long long) (u.fl & 0x8d5), memcmp(t.x0, u.x0, 32) ? "DIFFERS" : "ok");
        }
    }
    // VLDMXCSR / VSTMXCSR
    static const unsigned ok[] = {0x1f80, 0x0000, 0xffff, 0x9fc0, 0x3f80};
    for (unsigned i = 0; i < 5; i++) {
        unsigned v = ok[i], r = 0;
        __asm__ volatile("vldmxcsr %1\n vstmxcsr %0" : "=m"(r) : "m"(v));
        checks++;
        if (r != v && bad++ < 40) printf("FAIL vldmxcsr/vstmxcsr %#x: read %#x\n", v, r);
    }
    unsigned def = 0x1f80;
    __asm__ volatile("vldmxcsr %0" :: "m"(def));
    struct sigaction sa;
    memset(&sa, 0, sizeof sa);
    sa.sa_handler = on_segv;
    sa.sa_flags = SA_NODEFER;
    sigaction(SIGSEGV, &sa, NULL);
    sig = 0;
    unsigned badv = 0x11f80;
    if (!sigsetjmp(jb, 1))
        __asm__ volatile("vldmxcsr %0" :: "m"(badv));
    unsigned after = 0;
    __asm__ volatile("vstmxcsr %0" : "=m"(after));
    checks++;
    if ((sig != SIGSEGV || after != 0x1f80) && bad++ < 40) printf("FAIL vldmxcsr reserved bit: signal %d, mxcsr %#x\n", sig, after);
    printf("NAME: %s (%d forms, %lu checks, %lu mismatches)\n", bad ? "FAIL" : "PASS", NF + NP + 2, checks, bad);
    return bad != 0;
}''')
open(ARGS[0], 'w').write('\n'.join(o).replace('NAME: %s', NAME + ': %s'))
print(len(F) + len(PC), 'forms')
