#!/usr/bin/env python3
# Generates tests/manual/x86/amd64_misc_rm.c (usage: this script OUT.c).
import sys
SUF = {8: 'b', 16: 'w', 32: 'l', 64: 'q'}
D = {8: '%%dl', 16: '%%dx', 32: '%%edx', 64: '%%rdx'}
A = {8: '%%al', 16: '%%ax', 32: '%%eax', 64: '%%rax'}
N9 = {8: '%%r9b', 16: '%%r9w', 32: '%%r9d', 64: '%%r9'}
N10 = {8: '%%r10b', 16: '%%r10w', 32: '%%r10d', 64: '%%r10'}
o = []; w = o.append
w('''// Generated by tools/gen-amd64-misc-rm-test.py -- do not edit.
//
// MOVZX/MOVSX (0F B6/B7/BE/BF) and MOVSXD (63), IMUL r, r/m, imm (69/6B),
// INC/DEC (FE/FF /0 /1), NOT/NEG (F6/F7 /2 /3), OP $imm, AL/AX/EAX/RAX (04-3D,
// A8/A9), MOV $imm8, AH..BH -- every width, register
// (AL..BL, AH..BH, r9/r10) and memory forms, LOCK where it is legal -- against
// a model of the SDM made of masks, shifts and adds (the multiply is
// shift-and-add: IMUL is under test). Only defined flags are checked. Checked
// against real hardware (an AMD Ryzen).
#include <stdint.h>
#include <stdio.h>
#include <string.h>

static unsigned long checks, bad;
static void check(const char *what, long k, uint64_t got, uint64_t want) {
    checks++;
    if (got != want && bad++ < 40)
        printf("FAIL %s (%ld): %#llx, want %#llx\\n", what, k, (unsigned long long) got, (unsigned long long) want);
}
#define CF 0x1
#define PF 0x4
#define AF 0x10
#define ZF 0x40
#define SF 0x80
#define OF 0x800
#define ST (CF | PF | AF | ZF | SF | OF)
static uint64_t rs = 0x243f6a8885a308d3ull;
static uint64_t rnd(void) { rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17; return rs; }
static uint64_t mask(int bits) { return bits == 64 ? ~0ull : (1ull << bits) - 1; }
static int64_t sext(uint64_t v, int bits) { return bits == 64 ? (int64_t) v : (int64_t) (v << (64 - bits)) >> (64 - bits); }
static int parity(uint64_t v) { int p = 1; for (int i = 0; i < 8; i++) p ^= (v >> i) & 1; return p; }
static uint64_t wr(uint64_t old, uint64_t v, int bits, int hi) {
    if (bits == 8) return (old & ~(0xffull << (hi ? 8 : 0))) | ((v & 0xff) << (hi ? 8 : 0));
    return bits == 32 ? (v & mask(32)) : bits == 64 ? v : (old & ~mask(bits)) | (v & mask(bits));
}
// a*b mod 2^64 and whether the signed product overflows `bits`, by shift-and-add
static uint64_t smul(int64_t a, int64_t b, int bits, int *ov) {
    uint64_t ua = (uint64_t) a, ub = (uint64_t) b, lo = 0, hi = 0;
    int neg = (a < 0) != (b < 0);
    if (a < 0) ua = -ua;
    if (b < 0) ub = -ub;
    for (int i = 0; i < 64; i++) {
        if (!((ub >> i) & 1)) continue;
        uint64_t pl = i ? ua << i : ua, ph = i ? ua >> (64 - i) : 0;
        uint64_t n = lo + pl;
        hi += ph + (n < lo);
        lo = n;
    }
    if (neg) { lo = ~lo; hi = ~hi; lo += 1; if (lo == 0) hi += 1; }
    uint64_t r = lo & mask(bits);
    if (bits == 64) *ov = hi != (uint64_t) ((int64_t) lo >> 63);
    else *ov = (uint64_t) sext(r, bits) != lo || hi != (uint64_t) ((int64_t) lo >> 63);
    return r;
}
''')
forms = []
def add(**k): forms.append(k)
# fam 0 movx: sub = signed, sbits = source width, bits = dest width, src = 0 al / 1 ah / 2 r10 / 3 mem
for sgn, mn in ((0, 'movz'), (1, 'movs')):
    for sb, ss in ((8, 'b'), (16, 'w')):
        for db in (16, 32, 64):
            if db <= sb: continue
            name = f'{mn}{ss}{SUF[db]}'
            add(name=f'{name} al', fam=0, sub=sgn, sbits=sb, bits=db, src=0, asm=f'{name} {A[sb]}, {D[db]}')
            if sb == 8 and db != 64:     # AH cannot be encoded with REX.W
                add(name=f'{name} ah', fam=0, sub=sgn, sbits=sb, bits=db, src=1, asm=f'{name} %%ah, {D[db]}')
            add(name=f'{name} r10', fam=0, sub=sgn, sbits=sb, bits=db, src=2, r9=1, asm=f'{name} {N10[sb]}, {N9[db]}')
            add(name=f'{name} mem', fam=0, sub=sgn, sbits=sb, bits=db, src=3, asm=f'{name} (%%rsi), {D[db]}')
add(name='movslq eax', fam=0, sub=1, sbits=32, bits=64, src=0, asm='movslq %%eax, %%rdx')
add(name='movslq r10d', fam=0, sub=1, sbits=32, bits=64, src=2, r9=1, asm='movslq %%r10d, %%r9')
add(name='movslq mem', fam=0, sub=1, sbits=32, bits=64, src=3, asm='movslq (%%rsi), %%rdx')
# fam 1 imul imm: src 0 reg (rax), 2 r10, 3 mem; imm small (6B) and large (69)
for bits in (16, 32, 64):
    s = SUF[bits]
    for big in (0, 1):
        imm = '$IMMB' if big else '$IMMS'
        add(name=f'imul{s} {"69" if big else "6b"} reg', fam=1, bits=bits, src=0, big=big, asm=f'imul{s} {imm}, {A[bits]}, {D[bits]}')
        add(name=f'imul{s} {"69" if big else "6b"} r10', fam=1, bits=bits, src=2, big=big, r9=1, asm=f'imul{s} {imm}, {N10[bits]}, {N9[bits]}')
        add(name=f'imul{s} {"69" if big else "6b"} mem', fam=1, bits=bits, src=3, big=big, asm=f'imul{s} {imm}, (%%rsi), {D[bits]}')
# fam 2 inc/dec/not/neg on dst: where 0 dl / 1 dh / 2 r9 / 3 mem / 4 lock mem
for sub, op in enumerate(['inc', 'dec', 'not', 'neg']):
    for bits in (8, 16, 32, 64):
        s = SUF[bits]
        add(name=f'{op}{s} reg', fam=2, sub=sub, bits=bits, src=0, asm=f'{op}{s} {D[bits]}')
        if bits == 8:
            add(name=f'{op}b dh', fam=2, sub=sub, bits=8, src=1, asm=f'{op}b %%dh')
        add(name=f'{op}{s} r9', fam=2, sub=sub, bits=bits, src=2, r9=1, asm=f'{op}{s} {N9[bits]}')
        add(name=f'{op}{s} mem', fam=2, sub=sub, bits=bits, src=3, asm=f'{op}{s} (%%rsi)')
        add(name=f'lock {op}{s} mem', fam=2, sub=sub, bits=bits, src=3, asm=f'lock {op}{s} (%%rsi)')
# fam 3: OP $imm, AL/AX/EAX/RAX (the 04-3D/A8/A9 accumulator encodings; the
# accumulator is swapped into rdx's slot around it), and fam 4: MOV $imm8, AH..BH
ALU = ['add', 'or', 'adc', 'sbb', 'and', 'sub', 'xor', 'cmp', 'test']
for sub, op in enumerate(ALU):
    for bits in (8, 16, 32, 64):
        for big in ((0,) if bits == 8 else (0, 1)):
            if bits > 8 and not big and op == 'test':
                continue          # TEST has no sign-extended imm8 form
            add(name=f'{op}{SUF[bits]} imm{"32" if big else "8"},{A[bits][2:]}', fam=3, sub=sub, bits=bits, src=0, big=big,
                asm=f'xchg %%rax, %%rdx\\n {op}{SUF[bits]} {"$IMMB" if big else "$IMMS"}, {A[bits]}\\n xchg %%rax, %%rdx')
for r, nm in enumerate(['ah', 'ch', 'dh', 'bh']):
    add(name=f'movb imm,{nm}', fam=4, sub=r, bits=8, src=0, big=0,
        asm=f'push %%rax\\n push %%rcx\\n push %%rbx\\n mov %1, %%rax\\n mov %1, %%rcx\\n mov %1, %%rbx\\n movb $IMMS, %%{nm}\\n mov %%{nm[0]}x, %%dx\\n pop %%rbx\\n pop %%rcx\\n pop %%rax')
for i, f in enumerate(forms):
    f['imm'] = ((i * 2654435761) >> 7) & 0xffffffff
    sm = (f['imm'] & 0xff)
    if sm >= 0x80: sm -= 0x100
    bg = f['imm'] if f['imm'] < 0x80000000 else f['imm'] - 0x100000000
    if f.get('bits') == 16 and f.get('big'): bg = (f['imm'] & 0xffff) - (0x10000 if f['imm'] & 0x8000 else 0)
    if f.get('big') and -128 <= bg < 128: bg += 1000            # keep it a 69
    f['immv'] = bg if f.get('big') else sm
    a = f['asm'].replace('$IMMB', f'${bg}').replace('$IMMS', f'${sm}')
    if f.get('r9'):
        a = f'mov %1, %%r9\\n mov %2, %%r10\\n {a}\\n mov %%r9, %1'
    w(f'''__attribute__((noinline)) static void f{i}(uint64_t *d, uint64_t s, uint8_t *mem, uint64_t *fl) {{
    uint64_t rd = *d, f, fin = *fl;
    __asm__ volatile("push %4\\n popfq\\n {a}\\n pushfq\\n pop %0"
                     : "=&r"(f), "+d"(rd) : "a"(s), "S"(mem), "r"(fin) : "cc", "memory", "r9", "r10");
    *d = rd; *fl = f;
}}''')
w('struct form { const char *name; int fam, sub, sbits, bits, src; long long imm; void (*fn)(uint64_t *, uint64_t, uint8_t *, uint64_t *); };')
w('static const struct form forms[] = {')
for i, f in enumerate(forms):
    w(f'    {{"{f["name"]}", {f["fam"]}, {f.get("sub", 0)}, {f.get("sbits", 0)}, {f["bits"]}, {f["src"]}, {f["immv"]}LL, f{i}}},')
w('};')
w(f'#define NFORMS {len(forms)}')
w('''
static uint64_t pick(int k) {
    switch (k % 8) {
    case 0: return 0;
    case 1: return 1ull << (rnd() % 64);
    case 2: return ~0ull;
    case 3: return 0x8000000000000000ull >> (rnd() % 64) * 8 % 64;
    case 4: return 0x7full << ((rnd() % 8) * 8);
    default: return rnd();
    }
}

int main(void) {
    static uint8_t buf[64] __attribute__((aligned(16)));
    for (int k = 0; k < 2000; k++) {
        for (int fi = 0; fi < NFORMS; fi++) {
            const struct form *f = &forms[fi];
            int bits = f->bits;
            uint64_t m = mask(bits), msb = 1ull << (bits - 1);
            uint64_t d = pick(k + fi), s = pick(k * 3 + fi + 1), memv = pick(k * 5 + fi + 2);
            uint8_t *mem = buf + 16 + (k % 8);
            memcpy(mem, &memv, 8);
            uint64_t fin = 0x202 | (rnd() & ST);
            uint64_t d0 = d, fl = fin;
            f->fn(&d, s, mem, &fl);
            uint64_t cur; memcpy(&cur, mem, 8);
            uint64_t wd = d0, wmem = memv, wf = fin, def = ST;
            switch (f->fam) {
            case 0: { // MOVZX / MOVSX / MOVSXD: a destination register
                uint64_t v = f->src == 3 ? memv : f->src == 1 ? s >> 8 : s;
                v &= mask(f->sbits);
                if (f->sub) v = (uint64_t) sext(v, f->sbits);
                wd = wr(d0, v, bits, 0);
                break;
            }
            case 1: { // IMUL r, r/m, imm
                uint64_t v = f->src == 3 ? memv : s;
                int ov;
                uint64_t r = smul(sext(v & m, bits), f->imm, bits, &ov);
                wd = wr(d0, r, bits, 0);
                wf = (fin & ~(uint64_t) (CF | OF)) | (ov ? CF | OF : 0);
                def = CF | OF;
                break;
            }
            case 3: { // OP $imm, the accumulator (in rdx's slot here)
                int op = f->sub;
                uint64_t l = d0 & m, r = (uint64_t) f->imm & m, res;
                int cin = (fin & CF) != 0;
                wf = fin & ~(uint64_t) ST;
                if (op == 1 || op == 4 || op == 6 || op == 8) {
                    res = op == 1 ? l | r : op == 6 ? l ^ r : l & r;
                    def &= ~(uint64_t) AF;
                    wf |= (res == 0 ? ZF : 0) | (res & msb ? SF : 0) | (parity(res) ? PF : 0);
                } else {
                    int sub = op == 3 || op == 5 || op == 7, c = (op == 2 || op == 3) ? cin : 0;
                    res = (sub ? l - r - c : l + r + c) & m;
                    int cf = sub ? (l < r || (c && l == r)) : (res < l || (c && res == l));
                    int of = sub ? ((l ^ r) & (l ^ res) & msb) != 0 : (~(l ^ r) & (l ^ res) & msb) != 0;
                    wf |= (cf ? CF : 0) | (of ? OF : 0) | (res == 0 ? ZF : 0) | (res & msb ? SF : 0) |
                          (parity(res) ? PF : 0) | (((l ^ r ^ res) >> 4) & 1 ? AF : 0);
                }
                if (op != 7 && op != 8) wd = wr(d0, res, bits, 0);
                break;
            }
            case 4: { // MOV $imm8 into AH..BH; dx = that register's low word after
                uint64_t v = (d0 & ~0xff00ull) | (((uint64_t) f->imm & 0xff) << 8);
                wd = (d0 & ~0xffffull) | (v & 0xffff);
                def = 0;
                break;
            }
            case 2: { // INC DEC NOT NEG
                int hi = f->src == 1;
                uint64_t v = (f->src == 3 ? memv : hi ? d0 >> 8 : d0) & m, r;
                if (f->sub == 2) {
                    r = ~v & m;
                } else {
                    uint64_t l = f->sub == 3 ? 0 : v, rr = f->sub == 3 ? v : 1;
                    int sub = f->sub != 0;
                    r = (sub ? l - rr : l + rr) & m;
                    int cf = sub ? l < rr : r < l;
                    int of = sub ? ((l ^ rr) & (l ^ r) & msb) != 0 : (~(l ^ rr) & (l ^ r) & msb) != 0;
                    wf = fin & ~(uint64_t) ST;
                    wf |= (r == 0 ? ZF : 0) | (r & msb ? SF : 0) | (parity(r) ? PF : 0) |
                          (((l ^ rr ^ r) >> 4) & 1 ? AF : 0) | (of ? OF : 0);
                    if (f->sub == 3) wf |= cf ? CF : 0;          // NEG: CF = (src != 0)
                    else wf |= fin & CF;                          // INC/DEC keep CF
                }
                if (f->src == 3) wmem = (memv & ~m) | r;
                else wd = wr(d0, r, bits, hi);
                break;
            }
            }
            long id = fi * 10000 + k;
            check(f->name, id, fl & def, wf & def);
            check(f->name, id, d, wd);
            check(f->name, id, cur, wmem);
        }
    }
    printf("amd64_misc_rm: %s (%d forms, %lu checks, %lu mismatches)\\n", bad ? "FAIL" : "PASS", NFORMS, checks, bad);
    return bad != 0;
}''')
open(sys.argv[1], 'w').write('\n'.join(o))
print(len(forms), 'forms')
