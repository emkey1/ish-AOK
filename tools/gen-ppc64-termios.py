#!/usr/bin/env python3
# Writes kernel/ppc64_termios.h: powerpc's tty ioctl numbers and termios
# encoding against the generic ones the rest of the kernel uses.
#
#   tools/gen-ppc64-termios.py VALUES > kernel/ppc64_termios.h
#
# VALUES is "NAME PPC_VALUE GENERIC_VALUE" a line: the outputs of
# tools/ppc64-termios-values.c built for powerpc64le and for x86-64, joined on
# the name (join <(sort ppc) <(sort x86)).
import sys
v = {}
for line in open(sys.argv[1]):
    name, ppc, gen = line.split()
    v[name] = (int(ppc, 16), int(gen, 16))

IFLAG = 'IGNBRK BRKINT IGNPAR PARMRK INPCK ISTRIP INLCR IGNCR ICRNL IUCLC IXON IXANY IXOFF IMAXBEL IUTF8'.split()
OFLAG = 'OPOST OLCUC ONLCR OCRNL ONOCR ONLRET OFILL OFDEL'.split()
OFIELDS = [('NLDLY', 'NL0 NL1'), ('CRDLY', 'CR0 CR1 CR2 CR3'), ('TABDLY', 'TAB0 TAB1 TAB2 TAB3'),
           ('BSDLY', 'BS0 BS1'), ('VTDLY', 'VT0 VT1'), ('FFDLY', 'FF0 FF1')]
CFLAG = 'CSTOPB CREAD PARENB PARODD HUPCL CLOCAL CMSPAR CRTSCTS'.split()
LFLAG = 'ISIG ICANON XCASE ECHO ECHOE ECHOK ECHONL NOFLSH TOSTOP ECHOCTL ECHOPRT ECHOKE FLUSHO PENDIN IEXTEN EXTPROC'.split()
CC = 'VINTR VQUIT VERASE VKILL VEOF VTIME VMIN VSWTC VSTART VSTOP VSUSP VEOL VREPRINT VDISCARD VWERASE VLNEXT VEOL2'.split()
# The ioctls whose argument is the same on both: renumbered only. The termios
# ones (TCGETS ...) are converted by kernel/fs.c, and TCGETA's struct termio
# is not offered.
IOCTLS = '''TCSBRK TCXONC TCFLSH TIOCEXCL TIOCNXCL TIOCSCTTY TIOCGPGRP TIOCSPGRP TIOCOUTQ TIOCSTI TIOCGWINSZ
TIOCSWINSZ TIOCMGET TIOCMBIS TIOCMBIC TIOCMSET TIOCGSOFTCAR TIOCSSOFTCAR FIONREAD TIOCLINUX TIOCCONS TIOCGSERIAL
TIOCSSERIAL TIOCPKT FIONBIO TIOCNOTTY TIOCSETD TIOCGETD TCSBRKP TIOCSBRK TIOCCBRK TIOCGSID TIOCGRS485 TIOCSRS485
TIOCGPTN TIOCSPTLCK TIOCGDEV TIOCSIG TIOCVHANGUP TIOCGPKT TIOCGPTLCK TIOCGEXCL TIOCGPTPEER FIONCLEX FIOCLEX FIOASYNC
TIOCMIWAIT TIOCGICOUNT FIOQSIZE'''.split()

def bits(names):
    return ''.join('    {%#x, %#x}, // %s\n' % (v[n][0], v[n][1], n) for n in names if n in v)

o = []
o.append('// Generated by tools/gen-ppc64-termios.py: powerpc\'s tty ioctls and termios\n')
o.append('// encoding against the generic (x86) ones, {powerpc, generic} each.\n')
o.append('#ifndef KERNEL_PPC64_TERMIOS_H\n#define KERNEL_PPC64_TERMIOS_H\n\n')
o.append('struct ppc64_pair { unsigned ppc, gen; };\n\n')
o.append('static const struct ppc64_pair ppc64_tty_ioctls[] = {\n' + bits(IOCTLS) + '};\n\n')
o.append('static const struct ppc64_pair ppc64_iflags[] = {\n' + bits(IFLAG) + '};\n')
o.append('static const struct ppc64_pair ppc64_oflags[] = {\n' + bits(OFLAG) + '};\n')
o.append('static const struct ppc64_pair ppc64_cflags[] = {\n' + bits(CFLAG) + '};\n')
o.append('static const struct ppc64_pair ppc64_lflags[] = {\n' + bits(LFLAG) + '};\n\n')
o.append('// The multi-bit fields of oflag: the field\'s mask, then its values.\n')
o.append('struct ppc64_field { struct ppc64_pair mask; struct ppc64_pair values[4]; unsigned count; };\n')
o.append('static const struct ppc64_field ppc64_ofields[] = {\n')
for field, vals in OFIELDS:
    vals = vals.split()
    o.append('    {{%#x, %#x}, {%s}, %d}, // %s\n' % (v[field][0], v[field][1],
             ', '.join('{%#x, %#x}' % v[x] for x in vals), len(vals), field))
o.append('};\n\n')
o.append('// CSIZE: CS5..CS8\n')
o.append('static const struct ppc64_field ppc64_csize = {{%#x, %#x}, {%s}, 4};\n\n' % (
    v['CSIZE'][0], v['CSIZE'][1], ', '.join('{%#x, %#x}' % v[x] for x in ('CS5', 'CS6', 'CS7', 'CS8'))))
o.append('#define PPC64_CBAUD %#x\n#define PPC64_CIBAUD %#x\n' % (v['CBAUD'][0], v['CIBAUD'][0]))
o.append('#define GEN_CBAUD %#x\n#define GEN_CBAUDEX %#x\n#define GEN_CIBAUD %#x\n\n' % (v['CBAUD'][1], v['CBAUDEX'][1], v['CIBAUD'][1]))
o.append('// c_cc: the generic index of each powerpc index (-1: none)\n')
cc = [-1] * 19
for n in CC:
    if n in v and v[n][0] < 19:
        cc[v[n][0]] = v[n][1]
o.append('static const signed char ppc64_cc_to_gen[19] = {%s};\n\n' % ', '.join(str(x) for x in cc))
for n in ('TCGETS', 'TCSETS', 'TCSETSW', 'TCSETSF'):
    o.append('#define PPC64_%s %#x\n' % (n, v[n][0]))
o.append('\n#endif\n')
print(''.join(o))
