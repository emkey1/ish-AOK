#!/usr/bin/env python3
# Generates tests/manual/x86/amd64_vex_width.c, or with --i386
# i386_vex_width.c (usage: this script [--i386] OUT.c).
#
# The VEX ops that change width -- VCVTPS2PD, VCVTDQ2PD, VPMOVSX/ZX* (widen),
# VCVTPD2PS, VCVTPD2DQ, VCVTTPD2DQ (narrow), VCVTSS2SD/SD2SS (scalar, three-
# operand) -- VEX.128 and VEX.256, register and memory, against the SSE form
# on the same machine: a widening op's high half is the SSE op on the source
# advanced by what the low half consumed; a narrowing op's two SSE halves
# pack into the low 128 bits. Result and MXCSR flags under three modes.
import sys
I386 = '--i386' in sys.argv
ARGS = [a for a in sys.argv[1:] if a != '--i386']
NAME = 'i386_vex_width' if I386 else 'amd64_vex_width'
WIDEN = [('vcvtps2pd', 'cvtps2pd', 8, 1), ('vcvtdq2pd', 'cvtdq2pd', 8, 1)] + \
    [(f'vpmov{s}x{a}', f'pmov{s}x{a}', n, 0) for s in 'sz' for a, n in
     (('bw', 8), ('bd', 4), ('bq', 2), ('wd', 8), ('wq', 4), ('dq', 8))]
NARROW = [('vcvtpd2ps', 'cvtpd2ps'), ('vcvtpd2dq', 'cvtpd2dq'), ('vcvttpd2dq', 'cvttpd2dq')]
SCAL = [('vcvtss2sd', 'cvtss2sd'), ('vcvtsd2ss', 'cvtsd2ss')]
MODES = [0x1f80, 0x7f80, 0x9fc0]
o = []; w = o.append
w(f'''// Generated by tools/gen-vex-width-test.py{" --i386" if I386 else ""} -- do not edit.
//
// The width-changing VEX ops against their SSE forms (see the generator).
#pragma GCC target("avx2")
#include <stdint.h>
#include <stdio.h>
#include <string.h>
static unsigned long checks, bad;
static void check(const char *what, int k, const uint8_t *got, const uint8_t *want, unsigned gf, unsigned wf) {{
    checks++;
    if ((memcmp(got, want, 32) != 0 || gf != wf) && bad++ < 40) {{
        printf("FAIL %s (%d): flags %#x want %#x\\n  got ", what, k, gf, wf);
        for (int i = 31; i >= 0; i--) printf("%s%02x", i % 8 == 7 ? " " : "", got[i]);
        printf("\\n  want");
        for (int i = 31; i >= 0; i--) printf("%s%02x", i % 8 == 7 ? " " : "", want[i]);
        printf("\\n");
    }}
}}
static uint64_t rs = 0x9e3779b97f4a7c15ull;
static uint64_t rnd(void) {{ rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17; return rs; }}
static void ldmx(unsigned v) {{ __asm__ volatile("ldmxcsr %0" :: "m"(v)); }}
static unsigned stmx(void) {{ unsigned v; __asm__ volatile("stmxcsr %0" : "=m"(v)); return v; }}
struct st {{ uint8_t a[32], b[32], d[32], out[32], m[64]; }} __attribute__((aligned(32)));
static void fill(uint8_t *p, int n, int dbl) {{
    for (int i = 0; i < n; i += 8) {{
        uint64_t v = rnd();
        if ((v & 7) == 0) v = (v & 0x800fffffffffffffull) | ((uint64_t) ((v >> 40) & 1 ? 0x7ff : 0) << 52);
        else if (dbl) v = (v & 0x800fffffffffffffull) | ((uint64_t) (((v >> 52) % 400) + 800) << 52);
        memcpy(p + i, &v, 8);
    }}
}}
''')
for _, sop, *r in WIDEN + NARROW + SCAL:
    w(f'static void r_{sop}(const uint8_t *x, const uint8_t *y, uint8_t *r) {{ __asm__ volatile("movdqu (%0), %%xmm0\\n movdqu (%1), %%xmm1\\n {sop} %%xmm1, %%xmm0\\n movdqu %%xmm0, (%2)" :: "r"(x), "r"(y), "r"(r) : "memory", "xmm0", "xmm1"); }}')
fi = 0
forms = []
def vexfn(body):
    global fi
    w(f'''__attribute__((noinline)) static void f{fi}(struct st *t) {{
    __asm__ volatile("vmovdqu (%0), %%ymm2\\n vmovdqu 32(%0), %%ymm3\\n vmovdqu 64(%0), %%ymm1\\n"
                     "{body}\\n vmovdqu %%ymm1, 96(%0)\\n vzeroupper" :: "r"(t) : "memory", "xmm1", "xmm2", "xmm3");
}}''')
    fi += 1
    return fi - 1
for vop, sop, step, fp in WIDEN:
    for L, x in ((256, 'ymm'), (128, 'xmm')):
        for lab, body, src in (('reg', f'{vop} %%xmm3, %%{x}1', 'b'), ('mem', f'{vop} 128(%0), %%{x}1', 'm')):
            forms.append((vexfn(body), f'{vop} {L} {lab}', f'r_{sop}', 0, step, L, src, fp))
for vop, sop in NARROW:
    for L, x in ((256, 'ymm'), (128, 'xmm')):
        for lab, body, src in (('reg', f'{vop} %%{x}3, %%xmm1', 'b'), ('mem', f'{vop}{"y" if L == 256 else "x"} 128(%0), %%xmm1', 'm')):
            forms.append((vexfn(body), f'{vop} {L} {lab}', f'r_{sop}', 1, 0, L, src, 1))
for vop, sop in SCAL:
    for lab, body, src in (('reg', f'{vop} %%xmm3, %%xmm2, %%xmm1', 'b'), ('mem', f'{vop} 128(%0), %%xmm2, %%xmm1', 'm')):
        forms.append((vexfn(body), f'{vop} {lab}', f'r_{sop}', 2, 0, 128, src, 1))
w('static const struct { const char *name; void (*fn)(struct st *); void (*ref)(const uint8_t *, const uint8_t *, uint8_t *); int kind, step, L; char src; int fp; } forms[] = {')
for i, name, ref, kind, step, L, src, fp in forms:
    w(f'    {{"{name}", f{i}, {ref}, {kind}, {step}, {L}, \'{src}\', {fp}}},')
w('};')
w(f'#define NFORMS {len(forms)}')
w(f'static const unsigned modes[] = {{{", ".join(hex(m) for m in MODES)}}};')
w(r'''
int main(void) {
    static struct st t;
    for (int k = 0; k < 300; k++) {
        for (unsigned mi = 0; mi < 3; mi++) {
            for (int fi = 0; fi < NFORMS; fi++) {
                if (!forms[fi].fp && mi) continue;
                fill(t.a, 32, k & 1); fill(t.b, 32, k & 1); fill(t.d, 32, k & 1); fill(t.m, 64, k & 1);
                if (k & 2) for (int i = 0; i < 32; i += 4) { uint32_t v = (uint32_t) rnd(); if ((v & 3) == 0) v = 0x7fc00000 | (v & 0x80000000); memcpy(t.b + i, &v, 4); memcpy(t.m + i, &v, 4); }
                struct st in = t;
                ldmx(modes[mi]);
                forms[fi].fn(&t);
                unsigned gf = stmx() & 0x3f, wf = 0;
                const uint8_t *s = forms[fi].src == 'm' ? in.m : in.b;
                uint8_t want[32] = {0}, tmp[16], adv[32] = {0};
                if (forms[fi].kind == 0) {
                    ldmx(modes[mi]); forms[fi].ref(in.d, s, want); wf = stmx() & 0x3f;
                    if (forms[fi].L == 256) {
                        memcpy(adv, s + forms[fi].step, 16);
                        ldmx(modes[mi]); forms[fi].ref(in.d, adv, want + 16); wf |= stmx() & 0x3f;
                    }
                } else if (forms[fi].kind == 1) {
                    ldmx(modes[mi]); forms[fi].ref(in.d, s, tmp); wf = stmx() & 0x3f;
                    memcpy(want, tmp, 8);
                    if (forms[fi].L == 256) {
                        ldmx(modes[mi]); forms[fi].ref(in.d, s + 16, tmp); wf |= stmx() & 0x3f;
                        memcpy(want + 8, tmp, 8);
                    }
                } else {
                    ldmx(modes[mi]); forms[fi].ref(in.a, s, want); wf = stmx() & 0x3f;
                }
                check(forms[fi].name, k, t.out, want, gf, wf);
            }
        }
    }
    ldmx(0x1f80);
    printf("NAME: %s (%d forms, %lu checks, %lu mismatches)\n", bad ? "FAIL" : "PASS", NFORMS, checks, bad);
    return bad != 0;
}''')
open(ARGS[0], 'w').write('\n'.join(o).replace('NAME: %s', NAME + ': %s'))
print(len(forms), 'forms')
