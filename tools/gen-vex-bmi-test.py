#!/usr/bin/env python3
# Generates tests/manual/x86/amd64_vex_bmi.c, or with --i386 i386_vex_bmi.c
# (usage: this script [--i386] OUT.c).
#
# BMI1/BMI2 (ANDN BLSR BLSMSK BLSI BZHI PEXT PDEP MULX BEXTR SHLX SARX SHRX
# RORX), register and memory, 32 and (amd64) 64 bits, against a model: the
# results and all six arithmetic flags as an AMD Ryzen sets them -- the SDM
# leaves some undefined; this is camd's choice (BEXTR: AF 1, SF 0). camd runs
# it too.
import sys
I386 = '--i386' in sys.argv
ARGS = [a for a in sys.argv[1:] if a != '--i386']
NAME = 'i386_vex_bmi' if I386 else 'amd64_vex_bmi'
OPS = ['andn', 'blsr', 'blsmsk', 'blsi', 'bzhi', 'pext', 'pdep', 'mulx', 'bextr', 'shlx', 'sarx', 'shrx', 'rorx']
WIDTHS = [32] if I386 else [32, 64]
o = []; w = o.append
w(f'''// Generated by tools/gen-vex-bmi-test.py{" --i386" if I386 else ""} -- do not edit.
//
// BMI1/BMI2 against a model of an AMD Ryzen's results and flags (see the
// generator).
#pragma GCC target("bmi,bmi2")
#include <stdint.h>
#include <stdio.h>
#include <string.h>
static unsigned long checks, bad;
static uint64_t rs = 0x9e3779b97f4a7c15ull;
static uint64_t rnd(void) {{ rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17; return rs; }}
typedef unsigned long reg;
struct io {{ reg a, b, dx, r, r2, fl; reg m; }};
''')
forms = []
for wd in WIDTHS:
    s = '' if wd == 64 else 'k'
    def R(n): return f'%{s}{n}'
    for op in OPS:
        for mem in (0, 1):
            src = '%[m]' if mem else R('[b]')
            if op == 'andn': asm = f'andn {src}, {R("[a]")}, {R("[r]")}'
            elif op in ('blsr', 'blsmsk', 'blsi'): asm = f'{op} {src}, {R("[r]")}'
            elif op in ('bzhi', 'bextr', 'shlx', 'sarx', 'shrx'): asm = f'{op} {R("[a]")}, {src}, {R("[r]")}'
            elif op in ('pext', 'pdep'): asm = f'{op} {src}, {R("[a]")}, {R("[r]")}'
            elif op == 'mulx': asm = f'mulx {src}, {R("[r2]")}, {R("[r]")}'
            else: asm = f'rorx $13, {src}, {R("[r]")}'
            forms.append((f'{op}{wd} {"mem" if mem else "reg"}', op, wd, asm))
for i, (name, op, wd, asm) in enumerate(forms):
    w(f'''__attribute__((noinline)) static void f{i}(struct io *t) {{
    reg r = 0x1234, r2 = 0x5678, fl;
    __asm__ volatile("push %[fin]\\n popf\\n {asm}\\n pushf\\n pop %[fl]"
                     : [r] "+&r"(r), [r2] "+&r"(r2), [fl] "=r"(fl)
                     : [a] "r"(t->a), [b] "r"(t->b), [m] "m"(t->m), "d"(t->dx), [fin] "r"((reg) 0x8d7)
                     : "cc");
    t->r = r; t->r2 = r2; t->fl = fl;
}}''')
w('static const struct { const char *name; int op, w; void (*fn)(struct io *); } forms[] = {')
for i, (name, op, wd, asm) in enumerate(forms):
    w(f'    {{"{name}", {OPS.index(op)}, {wd}, f{i}}},')
w('};')
w(f'#define NF {len(forms)}')
w(r'''
static int par(uint64_t r) { return !__builtin_parity((unsigned) (r & 0xff)); }
// the model: r (and r2 for MULX), and the flags (or ~0 when the op keeps them)
static void model(int op, int w, uint64_t a, uint64_t b, uint64_t dx, uint64_t *r, uint64_t *r2, uint64_t *fl) {
    uint64_t m = w == 64 ? ~0ull : 0xffffffffull, x = 0;
    a &= m; b &= m; dx &= m;
    int cf = 0, flags = 1, bextr = 0;
    switch (op) {
    case 0: x = ~a & b; break;
    case 1: x = b & (b - 1); cf = b == 0; break;
    case 2: x = b ^ (b - 1); cf = b == 0; break;
    case 3: x = b & -b; cf = b != 0; break;
    case 4: { unsigned n = a & 0xff; if (n >= (unsigned) w) { x = b; cf = 1; } else x = b & ((1ull << n) - 1); break; }
    case 5: { int k = 0; for (int i = 0; i < w; i++) if ((b >> i) & 1) x |= ((a >> i) & 1) << k++; flags = 0; break; }
    case 6: { int k = 0; for (int i = 0; i < w; i++) if ((b >> i) & 1) x |= ((a >> k++) & 1) << i; flags = 0; break; }
    case 7: {
#if defined(__x86_64__)
              if (w == 64) { unsigned __int128 p = (unsigned __int128) dx * b; x = (uint64_t) (p >> 64); *r2 = (uint64_t) p; }
              else
#endif
              { uint64_t p = dx * b; x = p >> 32; *r2 = p & 0xffffffff; } flags = 0; break; }
    case 8: { unsigned s = a & 0xff, l = (a >> 8) & 0xff; x = s >= (unsigned) w ? 0 : b >> s; if (l < 64) x &= (1ull << l) - 1; bextr = 1; break; }
    case 9: x = b << (a & (w - 1)); flags = 0; break;
    case 10: x = (uint64_t) ((w == 64 ? (int64_t) b : (int64_t) (int32_t) b) >> (a & (w - 1))); flags = 0; break;
    case 11: x = b >> (a & (w - 1)); flags = 0; break;
    default: x = (b >> 13) | (b << (w - 13)); flags = 0; break;
    }
    x &= m;
    *r = x;
    if (!flags) { *fl = ~0ull; return; }
    uint64_t f = (uint64_t) cf | (uint64_t) par(x) << 2 | (uint64_t) (x == 0) << 6;
    if (bextr) f |= 0x10; else f |= ((x >> (w - 1)) & 1) << 7;
    *fl = f;
}
int main(void) {
    struct io t;
    for (int k = 0; k < 20000; k++) {
        for (int fi = 0; fi < NF; fi++) {
            t.a = (reg) rnd(); t.b = (reg) rnd(); t.dx = (reg) rnd();
            if (k % 7 == 0) t.b = 0;
            if (k % 5 == 0) t.a &= 0x7f7f;
            if (k % 11 == 0) t.b = (reg) 1 << (rnd() % (8 * sizeof(reg)));
            if (forms[fi].name[strlen(forms[fi].name) - 1] == 'm') t.m = t.b;
            t.m = t.b;
            forms[fi].fn(&t);
            uint64_t r, r2 = 0x5678, fl;
            model(forms[fi].op, forms[fi].w, t.a, t.b, t.dx, &r, &r2, &fl);
            if (forms[fi].w == 32) { r2 = forms[fi].op == 7 ? r2 : 0x5678; }
            checks++;
            uint64_t gfl = fl == ~0ull ? ~0ull : (t.fl & 0x8d5);
            if (fl == ~0ull && (t.fl & 0x8d5) != 0x8d5) gfl = t.fl & 0x8d5;   // flags must stay as they were (0x8d7)
            if (fl == ~0ull) fl = ~0ull, gfl = (t.fl & 0x8d5) == 0x8d5 ? ~0ull : (t.fl & 0x8d5);
            if (((uint64_t) t.r != r || (forms[fi].op == 7 && (uint64_t) t.r2 != r2) || gfl != fl) && bad++ < 40)
                printf("FAIL %s (%d): a %llx b %llx dx %llx -> r %llx r2 %llx fl %llx, want %llx %llx %llx\n", forms[fi].name, k,
                       (unsigned long long) t.a, (unsigned long long) t.b, (unsigned long long) t.dx, (unsigned long long) t.r,
                       (unsigned long long) t.r2, (unsigned long long) gfl, (unsigned long long) r, (unsigned long long) r2,
                       (unsigned long long) fl);
        }
    }
    printf("NAME: %s (%d forms, %lu checks, %lu mismatches)\n", bad ? "FAIL" : "PASS", NF, checks, bad);
    return bad != 0;
}''')
open(ARGS[0], 'w').write('\n'.join(o).replace('NAME: %s', NAME + ': %s'))
print(len(forms), 'forms')
