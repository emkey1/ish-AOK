#!/usr/bin/env python3
# Generates tests/manual/x86/amd64_sse_shift.c (usage: this script OUT.c), or
# with --i386 tests/manual/x86/i386_sse_shift.c: the same built -m32, xmm1
# and mm1 only, the memory count through %edi.
import sys
I386 = '--i386' in sys.argv
ARGS = [a for a in sys.argv[1:] if a != '--i386']
o = []; w = o.append
w('''// Generated by tools/gen-amd64-sse-shift-test.py -- do not edit.
//
// The packed integer shifts: PSRLW/D/Q, PSRAW/D, PSLLW/D/Q by an imm8
// (0F 71/72/73 /2 /4 /6), PSRLDQ/PSLLDQ (66 0F 73 /3 /7), and by a count in
// an XMM/MMX register or in memory (0F D1-D3, E1-E2, F1-F3) -- XMM (66) and
// MMX, xmm1/xmm9 (REX) -- against a per-lane model: a count past the lane
// width gives 0, or the sign for PSRA; the register/memory count is the
// whole low quadword. Checked against real hardware (an AMD Ryzen).
TARGET_PRAGMA#include <stdint.h>
#include <stdio.h>
#include <string.h>

static unsigned long checks, bad;
static void check(const char *what, long k, uint64_t got, uint64_t want) {
    checks++;
    if (got != want && bad++ < 40)
        printf("FAIL %s (%ld): %#llx, want %#llx\\n", what, k, (unsigned long long) got, (unsigned long long) want);
}
static uint64_t rs = 0x243f6a8885a308d3ull;
static uint64_t rnd(void) { rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17; return rs; }

// kind 0 srl, 1 sra, 2 sll; lane bits 16/32/64; bytes: 128 = dq form
static void model(int kind, int lane, int nbytes, const uint8_t *in, uint64_t count, uint8_t *out) {
    if (lane == 128) {           // PSRLDQ / PSLLDQ: whole bytes, count > 15 clears
        for (int i = 0; i < 16; i++) {
            int j = kind == 0 ? i + (int) count : i - (int) count;
            out[i] = count > 15 || j < 0 || j > 15 ? 0 : in[j];
        }
        return;
    }
    int lb = lane / 8;
    for (int e = 0; e < nbytes / lb; e++) {
        uint64_t v = 0;
        for (int b = 0; b < lb; b++) v |= (uint64_t) in[e * lb + b] << (8 * b);
        uint64_t m = lane == 64 ? ~0ull : (1ull << lane) - 1, msb = 1ull << (lane - 1), r;
        if (count >= (uint64_t) lane) {
            r = kind == 1 ? ((v & msb) ? m : 0) : 0;
        } else if (kind == 0) {
            r = v >> count;
        } else if (kind == 2) {
            r = (v << count) & m;
        } else {
            r = v >> count;
            if (v & msb) r |= m & ~(m >> count);
        }
        for (int b = 0; b < lb; b++) out[e * lb + b] = (uint8_t) (r >> (8 * b));
    }
}
''')
forms = []
SH = [('psrlw', 0, 16, 0x71, 2), ('psrld', 0, 32, 0x72, 2), ('psrlq', 0, 64, 0x73, 2),
      ('psraw', 1, 16, 0x71, 4), ('psrad', 1, 32, 0x72, 4),
      ('psllw', 2, 16, 0x71, 6), ('pslld', 2, 32, 0x72, 6), ('psllq', 2, 64, 0x73, 6)]
for name, kind, lane, _, _ in SH:
    for xmm in (1, 0):
        regs = ([('%%xmm1', '%%xmm2')] if I386 else [('%%xmm1', '%%xmm2'), ('%%xmm9', '%%xmm10')]) if xmm else [('%%mm1', '%%mm2')]
        for d, c in regs:
            forms.append(dict(name=f'{name} imm {d[2:]}', kind=kind, lane=lane, xmm=xmm, how=0, d=d, c=c, asm=f'{name} $IMM, {d}'))
            forms.append(dict(name=f'{name} reg {d[2:]}', kind=kind, lane=lane, xmm=xmm, how=1, d=d, c=c, asm=f'{name} {c}, {d}'))
            forms.append(dict(name=f'{name} mem {d[2:]}', kind=kind, lane=lane, xmm=xmm, how=2, d=d, c=c, asm=f'{name} (%%{"edi" if I386 else "rdi"}), {d}'))
for name, kind in (('psrldq', 0), ('pslldq', 2)):
    for d in (('%%xmm1',) if I386 else ('%%xmm1', '%%xmm9')):
        forms.append(dict(name=f'{name} {d[2:]}', kind=kind, lane=128, xmm=1, how=0, d=d, c='', asm=f'{name} $IMM, {d}'))
for i, f in enumerate(forms):
    f['imm'] = [0, 1, 3, 7, 8, 15, 16, 17, 31, 32, 33, 63, 64, 100, 255][i % 15] if f['lane'] != 128 else [0, 1, 5, 15, 16, 200][i % 6]
    ld = 'movdqu' if f['xmm'] else 'movq'
    a = f['asm'].replace('$IMM', '$%d' % f['imm'])
    c = f['c'] or '%%xmm2'
    tail = '' if f['xmm'] else '\\n emms'
    w(f'''__attribute__((noinline)) static void f{i}(uint8_t *v, uint8_t *cnt) {{
    __asm__ volatile("{ld} (%0), {f['d']}\\n {ld} (%1), {c}\\n {a}\\n {ld} {f['d']}, (%0){tail}"
                     :: "S"(v), "D"(cnt) : "memory", "xmm1", "xmm2"{'' if I386 else ', "xmm9", "xmm10", "mm1", "mm2"'});
}}''')
w('struct form { const char *name; int kind, lane, xmm, how, imm; void (*fn)(uint8_t *, uint8_t *); };')
w('static const struct form forms[] = {')
for i, f in enumerate(forms):
    w(f'    {{"{f["name"]}", {f["kind"]}, {f["lane"]}, {f["xmm"]}, {f["how"]}, {f["imm"]}, f{i}}},')
w('};')
w(f'#define NFORMS {len(forms)}')
w('''
int main(void) {
    static uint8_t v[16] __attribute__((aligned(16))), cnt[16] __attribute__((aligned(16))), in[16], want[16];
    static const uint64_t counts[] = {0, 1, 2, 7, 8, 15, 16, 17, 31, 32, 33, 63, 64, 65, 255, 256, 0x100000001ull, ~0ull};
    for (int k = 0; k < 3000; k++) {
        for (int fi = 0; fi < NFORMS; fi++) {
            const struct form *f = &forms[fi];
            for (int i = 0; i < 16; i++) in[i] = (uint8_t) rnd();
            if (k % 4 == 0) for (int i = 1; i < 16; i += 2) in[i] |= 0x80;   // negative lanes
            uint64_t c = f->how == 0 ? (uint64_t) f->imm : counts[(k + fi) % 18];
            if (f->how && k % 3 == 0) c = rnd() % 70;
            memcpy(v, in, 16);
            memcpy(cnt, &c, 8);
            uint64_t junk = rnd();
            memcpy(cnt + 8, &junk, 8);                  // only the low quadword counts
            f->fn(v, cnt);
            int nb = f->xmm ? 16 : 8;
            memcpy(want, in, 16);
            model(f->kind, f->lane, nb, in, c, want);
            uint64_t g0, g1, w0, w1;
            memcpy(&g0, v, 8); memcpy(&g1, v + 8, 8); memcpy(&w0, want, 8); memcpy(&w1, want + 8, 8);
            check(f->name, fi * 10000 + k, g0, w0);
            if (f->xmm) check(f->name, fi * 10000 + k, g1, w1);
        }
    }
    printf("NAME: %s (%d forms, %lu checks, %lu mismatches)\\n", bad ? "FAIL" : "PASS", NFORMS, checks, bad);
    return bad != 0;
}''')
out = '\n'.join(o).replace('"NAME: %s', '"' + ('i386_sse_shift' if I386 else 'amd64_sse_shift') + ': %s')
out = out.replace('TARGET_PRAGMA', '#pragma GCC target("mmx,sse2")\n' if I386 else '')
if I386:
    out = out.replace('gen-amd64-sse-shift-test.py -- do not edit', 'gen-amd64-sse-shift-test.py --i386 -- do not edit').replace('MMX, xmm1/xmm9 (REX)', 'MMX, xmm1, built -m32')
open(ARGS[0], 'w').write(out)
print(len(forms), 'forms')
