#!/usr/bin/env python3
# Generates tests/manual/x86/amd64_vex_mask.c, or with --i386
# i386_vex_mask.c (usage: this script [--i386] OUT.c).
#
# VMASKMOVPS/PD and VPMASKMOVD/Q, loads and stores, VEX.128 and VEX.256, and
# VMASKMOVDQU, against byte models; and the fault rule: an element masked off
# is not touched -- so one on an unmapped page does not fault -- and one
# masked on does (SIGSEGV at that page). camd runs it too.
import sys
I386 = '--i386' in sys.argv
ARGS = [a for a in sys.argv[1:] if a != '--i386']
NAME = 'i386_vex_mask' if I386 else 'amd64_vex_mask'
DI = 'edi' if I386 else 'rdi'
F = []
for op, esz in (('vmaskmovps', 4), ('vmaskmovpd', 8), ('vpmaskmovd', 4), ('vpmaskmovq', 8)):
    for L, x in ((256, 'ymm'), (128, 'xmm')):
        n = L // 8
        F.append((f'{op} {L} load', f'{op} 128(%0), %%{x}2, %%{x}1',
                  f'for (int i = 0; i < {n}; i += {esz}) if (a[i + {esz - 1}] & 0x80) memcpy(o + i, m + i, {esz});', 0))
        F.append((f'{op} {L} store', f'{op} %%{x}3, %%{x}2, 128(%0)',
                  f'memcpy(o, d, 32); for (int i = 0; i < {n}; i += {esz}) if (a[i + {esz - 1}] & 0x80) memcpy(mo + i, b + i, {esz});', 1))
F.append(('vmaskmovdqu', f'lea 128(%0), %%{DI}\\n vmaskmovdqu %%xmm2, %%xmm3', 'memcpy(o, d, 32); for (int i = 0; i < 16; i++) if (a[i] & 0x80) mo[i] = b[i];', 1))
o = []; w = o.append
w(f'''// Generated by tools/gen-vex-mask-test.py{" --i386" if I386 else ""} -- do not edit.
//
// The VEX masked moves against byte models, and their fault rule (see the
// generator).
#pragma GCC target("avx2")
#define _GNU_SOURCE
#include <setjmp.h>
#include <signal.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <sys/mman.h>
static unsigned long checks, bad;
static uint64_t rs = 0x9e3779b97f4a7c15ull;
static uint64_t rnd(void) {{ rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17; return rs; }}
struct st {{ uint8_t a[32], b[32], d[32], out[32], m[64]; }} __attribute__((aligned(32)));
''')
for i, (name, asm, model, st) in enumerate(F):
    w(f'''__attribute__((noinline)) static void f{i}(struct st *t) {{
    __asm__ volatile("vmovdqu (%0), %%ymm2\\n vmovdqu 32(%0), %%ymm3\\n vmovdqu 64(%0), %%ymm1\\n"
                     "{asm}\\n vmovdqu %%ymm1, 96(%0)\\n vzeroupper" :: "r"(t) : "memory", "{DI}", "xmm1", "xmm2", "xmm3");
}}
static void m{i}(const uint8_t *a, const uint8_t *b, const uint8_t *d, const uint8_t *m, uint8_t *o, uint8_t *mo) {{ (void) b; (void) d; (void) m; (void) mo; {model} }}''')
w('static const struct { const char *name; void (*fn)(struct st *); void (*model)(const uint8_t *, const uint8_t *, const uint8_t *, const uint8_t *, uint8_t *, uint8_t *); } forms[] = {')
for i, (name, asm, model, st) in enumerate(F):
    w(f'    {{"{name}", f{i}, m{i}}},')
w('};')
w(f'#define NF {len(F)}')
w(r'''
static sigjmp_buf jb;
static volatile int sig;
static volatile uintptr_t fault_addr;
static void on_segv(int s, siginfo_t *si, void *c) { (void) c; sig = s; fault_addr = (uintptr_t) si->si_addr; siglongjmp(jb, 1); }
int main(void) {
    static struct st t, u;
    for (int k = 0; k < 2000; k++) {
        for (int fi = 0; fi < NF; fi++) {
            for (int i = 0; i < 32; i++) { t.a[i] = (uint8_t) rnd(); t.b[i] = (uint8_t) rnd(); t.d[i] = (uint8_t) rnd(); }
            for (int i = 0; i < 64; i++) t.m[i] = (uint8_t) rnd();
            u = t;
            forms[fi].fn(&t);
            uint8_t o[32] = {0}, mo[64];
            memcpy(mo, u.m, 64);
            forms[fi].model(u.a, u.b, u.d, u.m, o, mo);
            checks++;
            if ((memcmp(t.out, o, 32) || memcmp(t.m, mo, 64)) && bad++ < 40) printf("FAIL %s (%d)\n", forms[fi].name, k);
        }
    }
    // the fault rule: a 32-byte operand whose high half lies on an unmapped page
    struct sigaction sa;
    memset(&sa, 0, sizeof sa);
    sa.sa_sigaction = on_segv;
    sa.sa_flags = SA_SIGINFO | SA_NODEFER;
    sigaction(SIGSEGV, &sa, NULL);
    uint8_t *pg = mmap(NULL, 8192, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
    munmap(pg + 4096, 4096);
    uint8_t *p = pg + 4096 - 16;
    for (int i = 0; i < 16; i++) p[i] = (uint8_t) i;
    static uint8_t lo_mask[32] __attribute__((aligned(32))), all_mask[32] __attribute__((aligned(32)));
    for (int i = 0; i < 32; i++) { lo_mask[i] = i < 16 ? 0x80 : 0; all_mask[i] = 0x80; }
    for (int store = 0; store < 2; store++) {
        for (int all = 0; all < 2; all++) {
            sig = 0; fault_addr = 0;
            if (!sigsetjmp(jb, 1)) {
                if (store)
                    __asm__ volatile("vmovdqu (%0), %%ymm2\n vmovdqu (%0), %%ymm3\n vmaskmovps %%ymm3, %%ymm2, (%1)\n vzeroupper"
                                     :: "r"(all ? all_mask : lo_mask), "r"(p) : "memory", "xmm2", "xmm3");
                else
                    __asm__ volatile("vmovdqu (%0), %%ymm2\n vmaskmovps (%1), %%ymm2, %%ymm3\n vzeroupper"
                                     :: "r"(all ? all_mask : lo_mask), "r"(p) : "memory", "xmm2", "xmm3");
            }
            checks++;
            int want = all ? SIGSEGV : 0;
            if ((sig != want || (all && fault_addr != (uintptr_t) (pg + 4096))) && bad++ < 40)
                printf("FAIL fault rule (%s, %s mask): signal %d (want %d), at %#lx\n", store ? "store" : "load",
                       all ? "all" : "low", sig, want, (unsigned long) fault_addr);
        }
    }
    printf("NAME: %s (%d forms, %lu checks, %lu mismatches)\n", bad ? "FAIL" : "PASS", NF + 4, checks, bad);
    return bad != 0;
}''')
open(ARGS[0], 'w').write('\n'.join(o).replace('NAME: %s', NAME + ': %s'))
print(len(F), 'forms')
