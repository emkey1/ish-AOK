#!/usr/bin/env python3
"""Generate the book's data appendices from the tree.

Four appendices are derived rather than written, so they cannot drift from the
code they describe:

    C  syscall coverage      <- kernel/calls.c
    D  /proc/ish reference   <- fs/proc/ish.c
    E  knobs                 <- getenv() across the tree, meson_options.txt
    F  the regression suite  <- tests/manual/*.c, fs/aok-tests.manifest

Run from the repository root:  python3 docs/book/appendices/generate.py
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__)))))
OUT = os.path.join(ROOT, "docs", "book", "appendices")

HEADER = ("<!-- GENERATED by docs/book/appendices/generate.py -- do not edit by hand. -->\n"
          "<!-- Regenerate after changing the sources named at the foot of the file. -->\n\n")


def read(path):
    with open(os.path.join(ROOT, path), errors="replace") as f:
        return f.read()


# ---------------------------------------------------------------- appendix C

TABLES = [
    ("i386", "i386_syscall_table"),
    ("amd64", "amd64_syscall_table"),
    ("arm64 / riscv64", "arm64_syscall_table"),
]

ENTRY = re.compile(r"^\s*\[(\d+)\]\s*=\s*\(syscall_t\)\s*([A-Za-z0-9_]+)\s*,?\s*(?://\s*(.*))?$")


def parse_tables(src):
    lines = src.split("\n")
    starts = {}
    for i, line in enumerate(lines):
        m = re.match(r"static syscall_t ([a-z0-9_]+)\[[0-9]*\]\s*=\s*\{", line)
        if m:
            starts[m.group(1)] = i

    tables = {}
    for name, start in starts.items():
        entries = {}
        depth = 0
        for line in lines[start:]:
            depth += line.count("{") - line.count("}")
            m = ENTRY.match(line)
            if m:
                num, fn, comment = int(m.group(1)), m.group(2), (m.group(3) or "").strip()
                entries[num] = (fn, comment)
            if depth <= 0 and line.strip().endswith("};"):
                break
        tables[name] = entries
    return tables


def classify(fn, comment):
    if fn == "syscall_stub":
        return "stub", "returns ENOSYS, logged"
    if fn == "syscall_stub_silent":
        return "stub (silent)", "returns ENOSYS, not logged"
    if fn == "syscall_stub_success":
        return "stub (success)", "accepted and ignored"
    if fn == "syscall_stub_eopnotsupp":
        return "stub", "returns EOPNOTSUPP"
    if "dispatched natively" in comment or "full-width" in comment:
        return "native dispatch", comment
    return "implemented", comment


def gen_c():
    src = read("kernel/calls.c")
    tables = parse_tables(src)
    out = [HEADER, "# Appendix C. Syscall coverage\n",
           "Generated from `kernel/calls.c`. Chapter 11's warning applies to every row:",
           "**a table entry is not a reachable syscall.** Entries marked *native dispatch*",
           "are handled full-width before the table is consulted, and the entry exists only",
           "so a NULL check passes — editing it changes nothing.\n"]

    counts = []
    for label, tname in TABLES:
        entries = tables.get(tname, {})
        kinds = {}
        for num, (fn, comment) in entries.items():
            kind, _ = classify(fn, comment)
            kinds[kind] = kinds.get(kind, 0) + 1
        counts.append((label, len(entries), kinds))

    out.append("## Summary\n")
    out.append("| table | entries | implemented | native dispatch | stubs |")
    out.append("|---|--:|--:|--:|--:|")
    for label, total, kinds in counts:
        stubs = sum(v for k, v in kinds.items() if k.startswith("stub"))
        out.append("| %s | %d | %d | %d | %d |" % (
            label, total, kinds.get("implemented", 0),
            kinds.get("native dispatch", 0), stubs))
    out.append("")
    out.append("riscv64 shares arm64's table: both are asm-generic ABIs with identical")
    out.append("numbering (Chapter 7).\n")

    for label, tname in TABLES:
        entries = tables.get(tname, {})
        if not entries:
            continue
        out.append("## %s\n" % label)
        out.append("| # | handler | kind | note |")
        out.append("|--:|---|---|---|")
        for num in sorted(entries):
            fn, comment = entries[num]
            kind, note = classify(fn, comment)
            note = note.replace("|", "\\|")
            if len(note) > 90:
                note = note[:87] + "..."
            out.append("| %d | `%s` | %s | %s |" % (num, fn, kind, note))
        out.append("")

    out.append("---\n")
    out.append("*Source:* [kernel/calls.c](../../../kernel/calls.c). "
               "Stubs that are absent from a table entirely return `ENOSYS` "
               "through the NULL path, and numbers past the table's end deliver "
               "`SIGSYS` (Chapter 11).")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- appendix D

def gen_d():
    src = read("fs/proc/ish.c")
    names = []
    for m in re.finditer(r'\{\s*"([a-z0-9_]+)"\s*,', src):
        if m.group(1) not in names:
            names.append(m.group(1))
    dirs = re.findall(r'"([a-z0-9_]+)"[^\n]*S_IFDIR', src)

    out = [HEADER, "# Appendix D. `/proc/ish` reference\n",
           "AOK's own addition to procfs — the guest asking about the app it is running",
           "inside. Nothing on real Linux has it. Chapter 18 covers the design; this is the",
           "inventory, generated from `fs/proc/ish.c`.\n",
           "## Nodes\n"]
    for n in sorted(names):
        kind = "directory" if n in dirs else "file"
        out.append("- `/proc/ish/%s` (%s)" % (n, kind))
    out.append("")
    out.append("## The ones that do more than report\n")
    out.append("- **`defaults/`** — one file per app preference, values as JSON. `0444`,")
    out.append("  root-writable; a write goes through the same validation the Settings")
    out.append("  screen uses, and removing an entry resets that preference (Chapter 18).")
    out.append("- **`<arch>_jit_fuse`** — the instruction-fusion mask, readable and writable")
    out.append("  at run time, consumed at translation time. The measurement surface behind")
    out.append("  Chapters 6 and 38.")
    out.append("- **`roots`** — the root manager. Reading lists roots, the catalogue and the")
    out.append("  current job; writing accumulates `key=value` lines until `run` (Chapter 30).")
    out.append("")
    out.append("---\n")
    out.append("*Source:* [fs/proc/ish.c](../../../fs/proc/ish.c), "
               "[opt/AOK/docs/proc-ish.md](../../../opt/AOK/docs/proc-ish.md).")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- appendix E

def gen_e():
    envs = {}
    for dirpath, dirnames, filenames in os.walk(ROOT):
        # Skip build trees, vendored code, and any dot-directory: another
        # session's git worktrees live under .claude/ and would otherwise be
        # scanned as though they were part of this checkout.
        dirnames[:] = [d for d in dirnames
                       if not d.startswith(".")
                       and d not in {"build", "deps", "e2e_out", "subprojects"}
                       and not d.startswith("build-")]
        for fn in filenames:
            if not fn.endswith((".c", ".m", ".h", ".mm", ".swift")):
                continue
            path = os.path.join(dirpath, fn)
            rel = os.path.relpath(path, ROOT)
            try:
                with open(path, errors="replace") as f:
                    text = f.read()
            except OSError:
                continue
            for m in re.finditer(r'getenv\(\s*"(ISH_[A-Z0-9_]+)"', text):
                envs.setdefault(m.group(1), set()).add(rel)

    opts = []
    for m in re.finditer(r"option\('([a-z0-9_]+)'[^)]*?type: *'([a-z]+)'"
                         r"(?:[^)]*?value: *([^,)]+))?", read("meson_options.txt"), re.S):
        opts.append((m.group(1), m.group(2), (m.group(3) or "").strip()))

    out = [HEADER, "# Appendix E. Knobs\n",
           "Every `ISH_*` environment variable the tree reads, and every meson option.",
           "Generated by scanning for `getenv(\"ISH_...\")` and parsing `meson_options.txt`.\n",
           "Environment variables are read by the CLI build and, where noted in the source,",
           "by the app; several have app-side equivalents under `/proc/ish/defaults`",
           "(Appendix D).\n",
           "## Environment variables\n",
           "| variable | read in |", "|---|---|"]
    for k in sorted(envs):
        where = ", ".join("`%s`" % p for p in sorted(envs[k])[:3])
        if len(envs[k]) > 3:
            where += " (+%d more)" % (len(envs[k]) - 3)
        out.append("| `%s` | %s |" % (k, where))
    out.append("")
    out.append("## Build options\n")
    out.append("| option | type | default |")
    out.append("|---|---|---|")
    for name, typ, val in opts:
        out.append("| `%s` | %s | %s |" % (name, typ, val.replace("|", "\\|")))
    out.append("")
    out.append("---\n")
    out.append("*Sources:* [meson_options.txt](../../../meson_options.txt), and "
               "`getenv` call sites across `emu/`, `jit/`, `kernel/`, `fs/`, `util/`, "
               "`platform/`, `tools/` and `app/`.")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- appendix F

def first_comment(text):
    """The test's own one-line description, from its leading comment block."""
    lines = text.split("\n")
    buf = []
    for line in lines[:40]:
        s = line.strip()
        if s.startswith("//"):
            body = s[2:].strip()
            if not body and buf:
                break
            if body:
                buf.append(body)
        elif s.startswith("/*"):
            body = s[2:].strip(" *")
            if body:
                buf.append(body)
        elif buf:
            break
        elif s.startswith("#include") or s.startswith("#define"):
            break
    if not buf:
        return ""
    text = " ".join(buf)
    text = re.sub(r"\s+", " ", text).strip()
    if len(text) > 150:
        text = text[:147].rsplit(" ", 1)[0] + "..."
    return text


def gen_f():
    tests_dir = os.path.join(ROOT, "tests", "manual")
    manifest = read("fs/aok-tests.manifest")
    listed = set()
    for line in manifest.split("\n"):
        line = line.strip()
        if line and not line.startswith("#"):
            listed.add(line)

    # Walk, do not listdir: the per-architecture tests live in tests/manual/x86,
    # arm64, riscv64 and crypto, the manifest carries them with those prefixes,
    # and a flat listing would silently drop them from the table and the count.
    names = []
    for dirpath, dirnames, filenames in os.walk(tests_dir):
        dirnames.sort()
        for fn in filenames:
            if fn.endswith(".c"):
                names.append(os.path.relpath(os.path.join(dirpath, fn), tests_dir))

    rows = []
    for rel in sorted(names):
        with open(os.path.join(tests_dir, rel), errors="replace") as f:
            text = f.read()
        rows.append((rel, first_comment(text), rel in listed))

    shipped = sum(1 for _, _, s in rows if s)
    out = [HEADER, "# Appendix F. The regression suite, annotated\n",
           "%d C programs in `tests/manual/`, of which **%d are listed in "
           "`fs/aok-tests.manifest`** and therefore reach the device at `/AOK/tests`."
           % (len(rows), shipped),
           "",
           "A row with a directory prefix is a per-architecture or accelerator test, kept",
           "in a subdirectory of `tests/manual/` and registered under that same prefix.",
           "",
           "A test missing from the manifest is silently absent on device — it does not",
           "fail, it does not appear, and the run reports success without it (Chapter 9).",
           "Descriptions are the tests' own leading comments, so a blank one is a test that",
           "does not say what it is for.\n",
           "| test | ships | what it is for |", "|---|:-:|---|"]
    for fn, desc, ship in rows:
        desc = desc.replace("|", "\\|")
        out.append("| `%s` | %s | %s |" % (fn, "yes" if ship else "—", desc))
    out.append("")
    out.append("---\n")
    out.append("*Sources:* `tests/manual/`, "
               "[fs/aok-tests.manifest](../../../fs/aok-tests.manifest). "
               "Registration also requires two lines in "
               "`tests/manual/setup-regressions.sh` (Chapter 9).")
    return "\n".join(out) + "\n"


def main():
    for name, fn in (("appendix-c-syscall-coverage.md", gen_c),
                     ("appendix-d-proc-ish.md", gen_d),
                     ("appendix-e-knobs.md", gen_e),
                     ("appendix-f-regression-suite.md", gen_f)):
        text = fn()
        with open(os.path.join(OUT, name), "w") as f:
            f.write(text)
        print("%-40s %6d bytes" % (name, len(text)))


if __name__ == "__main__":
    main()
